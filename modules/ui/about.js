// Сгенерировано из philosophy_graph.html — правки вносить сюда, не в исходник.
import { DATA } from '../core/ns.js';

function buildAboutText() {
      const counts = {
        concepts: DATA.concepts.length, relations: DATA.relations.length,
        philosophers: DATA.philosophers.length, traditions: DATA.traditions.length,
        rubrics: DATA.rubrics.length, relationTypes: DATA.relationTypes.length,
      };
      const years = DATA.philosophers.map(p => p.birth).filter(year => typeof year === 'number');
      const earliest = Math.min(...years), latest = Math.max(...years);
      const century = year => year < 0 ? Math.abs(year) + ' до н.э.' : String(year);

      const row = (what, how) => `<tr><td>${what}</td><td>${how}</td></tr>`;

      return `
        <h2>ΦilosΦaira</h2>
        <div class="about-lead">Граф философских концепций: карта понятий европейской
          философии и связей между ними — что из чего выросло, что чему противоречит,
          что на что похоже.</div>

        <h3>Что в базе</h3>
        <table>
          ${row('Концепции', `${counts.concepts} — понятия, каждое принадлежит философу`)}
          ${row('Связи', `${counts.relations} по ${counts.relationTypes} типам: влияние, развитие, критика,
            противопоставление, предпосылка и другие`)}
          ${row('Философы', `${counts.philosophers}, от ${century(earliest)} до ${century(latest)}`)}
          ${row('Традиции', `${counts.traditions} — школы и направления`)}
          ${row('Рубрики', `${counts.rubrics} — разделы философии: онтология, этика и прочие`)}
        </table>

        <h3>Граф</h3>
        <table>
          ${row('Щелчок по узлу', 'подсветить соседей; несмежные связи гаснут')}
          ${row('Ctrl+щелчок', 'добавить узел или связь к выбору, повторный — снять')}
          ${row('Двойной щелчок', 'открыть окно концепции')}
          ${row('Щелчок по связи', 'открыть окно связи')}
          ${row('Перетаскивание', 'сдвинуть узел; отпустите — он останется свободным')}
          ${row('Колесо', 'масштаб; перетаскивание пустого места — сдвиг полотна')}
          ${row('Наведение', 'подсказка с описанием узла или связи')}
          ${row('Состояния', `выбранная концепция — жёлтый ободок, подсвеченная — белый
            потолще со свечением, обычная — тонкий белый, приглушённая — полупрозрачная`)}
        </table>

        <h3>Легенда слева</h3>
        <table>
          ${row('Галочки', 'показать или скрыть философов, типы связей, рубрики, традиции')}
          ${row('Заголовки разделов', 'свернуть или развернуть раздел')}
          ${row('Щелчок по строке философа', `выбрать его на графе: концепции подсвечиваются,
            соседи по внешним связям остаются видны, прочее гаснет`)}
          ${row('Ctrl+щелчок по строке', 'добавить философа к выбору')}
          ${row('Двойной щелчок по строке', 'окно философа')}
          ${row('Поиск', `раскрывается кнопкой; три вида — философ, концепция, связь.
            Связь ищется по двум концам, и второй сужает выбор первого`)}
          ${row('Скрытая отбором', `находится и помечается; выбор показывает её ПОВЕРХ
            отбора, а в легенде появляется кнопка возврата`)}
        </table>

        <h3>Поиск пути</h3>
        <table>
          ${row('Откуда и куда', 'выбор концепции из полного списка или печатью')}
          ${row('Веса', 'сильные связи считаются более короткими')}
          ${row('Направленность', 'идти только по стрелке связи')}
          ${row('Хронология', 'режимы: строгий, умеренный, свободный и «без разрывов»')}
          ${row('Без разрывов', `время идёт только в одну сторону. Если цель раньше
            источника, путь читается как родословная — «восходит к». Прочие режимы
            проверяют каждую связь по отдельности, поэтому путь может уйти вперёд на
            века и вернуться назад`)}
          ${row('Описания пути', 'узлы и связи по порядку, с годами и традициями')}
        </table>

        <h3>Статистика</h3>
        <table>
          ${row('39 видов', 'от простых счётчиков до метрик влияния и напряжения')}
          ${row('Область счёта', 'по всему графу или только по видимой части')}
          ${row('Нормировка', 'сырые числа или приведённые к общей шкале')}
          ${row('Визуализировать размером', `узлы меняют размер по метрике; окно
            закрывается, а в легенде появляется кнопка сброса`)}
        </table>

        <!-- Раздел о панели контроля убран намеренно: у каждой её кнопки
             есть подсказка при наведении, и перечень здесь только устаревал
             бы вслед за панелью, ничего не добавляя. -->
      `;
    }

function openAboutModal() {
      const box = document.getElementById('aboutContent');
      if (box) box.innerHTML = buildAboutText();
      document.getElementById('aboutModal').classList.add('show');
    }

function closeAboutModal() {
      document.getElementById('aboutModal').classList.remove('show');
    }

function onAboutBackdropClick(ev) {
      if (ev.target && ev.target.id === 'aboutModal') closeAboutModal();
    }

export { buildAboutText, closeAboutModal, onAboutBackdropClick, openAboutModal };
