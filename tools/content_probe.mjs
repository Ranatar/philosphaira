#!/usr/bin/env node
// СОХРАННОСТЬ СОДЕРЖАНИЯ (`content_probe`).
//
// ПОВОД. 25 августа я переименовывал свои идентификаторы на латиницу и
// применил замену ПО ВСЕМУ ФАЙЛУ. Слова `середина` и `взамен` — обычные
// русские, и они есть не только в коде: в описаниях Ансельма и Декарта, в
// толкованиях блага и логоса, в НАЗВАНИИ концепции «Золотая середина».
// Автозамена испортила содержание. Нашёл не прибор и не я — автор.
//
// ЧТО ЭТО ЗА ПРИБОР. Он не проверяет правильность текстов: судить о них
// может только человек. Он проверяет, что текст НЕ ИЗМЕНИЛСЯ ТАМ, ГДЕ ЕГО
// не собирались менять, — сверяя нынешний исходник с отпечатком, снятым
// когда содержание было заведомо цело.
//
//   node tools/content_probe.mjs                 # проверить
//   node tools/content_probe.mjs учредить        # снять отпечаток заново
//   node tools/content_probe.mjs учредить --правка-содержания
//
// ДВА РОДА ПРАВОК РАЗЛИЧАЮТСЯ НАРОЧНО. Правка кода не должна менять ни
// одного описания — тогда прибор молчит. Правка содержания меняет их
// намеренно — тогда отпечаток учреждается заново, и это осознанный шаг с
// отдельным доводом в команде, а не молчаливое согласие.
//
// ПОЧЕМУ ОТПЕЧАТОК, А НЕ КОПИЯ. Хранить рядом второй экземпляр 2210
// описаний значит завести второй источник правды, который однажды разойдётся
// с первым. Хеш на поле плюс общее число полей ловит и правку, и пропажу, и
// приписку — а весит килобайты.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { ИСХОДНИК, КОРЕНЬ } from './paths.mjs';

const ОТПЕЧАТОК = path.join(КОРЕНЬ, 'baseline', 'content.json');

// Поля, которые видит ЧИТАТЕЛЬ. Заголовки окон, подписи кнопок и прочая
// обстановка сюда не входят: их стережёт обход, снимающий разметку. Здесь —
// то, ради чего graph вообще существует.
const ПОЛЯ = ['description', 'extendedDescription', 'label', 'name', 'nameRu'];

// ВТОРОЙ РОД ТЕКСТА — ТОТ, ЧТО ЧИТАЕТ ПОЛЬЗОВАТЕЛЬ В ОКНАХ. Подписи кнопок,
// заголовки, сообщения об ошибках, пояснения под полями. Их больше тысячи, и
// автозамена по образцу калечит их так же охотно, как описания: «Учитывать
// веса» и «Золотая середина» для регулярного выражения неразличимы.
//
// Обход снимков (`sweep_all`) стережёт лишь то, до чего добирается щелчками;
// сообщения редких состояний — «Не удалось определить связь для удаления» —
// не попадают в него никогда.

function собратьЗначения(текст) {
  const итог = {};
  for (const поле of ПОЛЯ) {
    // Значения лежат в записях данных как `поле: "…"`, с экранированными
    // кавычками внутри. Ленивый разбор до незаэкранированной кавычки.
    const образец = new RegExp(поле + ': "((?:[^"\\\\]|\\\\.)*)"', 'g');
    итог[поле] = [...текст.matchAll(образец)].map(с => с[1]);
  }
  return итог;
}

const хеш = с => crypto.createHash('sha256').update(с).digest('hex').slice(0, 16);

function отпечатокСодержания(текст) {
  const значения = собратьЗначения(текст);
  const итог = {};
  for (const [поле, список] of Object.entries(значения)) {
    итог[поле] = { сколько: список.length, хеши: список.map(хеш) };
  }
  итог['ИНТЕРФЕЙС'] = отпечатокИнтерфейса(текст, значения);
  return итог;
}

/**
 * Кириллица, которую видит пользователь, ЗА ВЫЧЕТОМ полей данных: строковые
 * литералы и текстовые узлы разметки.
 *
 * Отпечаток берётся от УПОРЯДОЧЕННОГО МНОЖЕСТВА, а не от последовательности:
 * перестановка функций в файле не должна краснить прибор, а пропажа или
 * порча строки — должна.
 */
function отпечатокИнтерфейса(текст, значенияПолей) {
  const данные = new Set(Object.values(значенияПолей).flat());
  const строки = new Set();
  // ОБРЫВКИ КОДА ОТСЕИВАЮТСЯ. Внутри шаблонных строк кавычки стоят и вокруг
  // выражений: `+ коды.map(к => escapeAttr(к)).join(` для образца неотличим
  // от подписи кнопки. Прибор, краснеющий на каждой правке кода, перестанут
  // читать — и он пропустит настоящую порчу.
  const ПРИЗНАКИ_КОДА = /=>|===|!==|&&|\|\||\$\{|\.\w+\(|document\.|window\.|\bfunction\b/;
  // ОБРЫВКИ СКЛЕЙКИ. Строка вида `+ (флаги.direction ?` — не подпись, а
  // кусок выражения, попавший между кавычками при переносе строки. Признаки
  // те же, что у любого обрывка: начинается со склейки, обрывается на
  // открытой скобке или тернарном вопросе.
  // ОСТОРОЖНО С ШИРОТОЙ ОБРАЗЦА. Первая редакция отсеивала и всё, что
  // начинается со скобки, — и съела настоящие подписи вроде
  // `)" data-tip="Вход">🔑</button>`. Прибор, чинимый вслепую, начинает
  // терять то, ради чего заведён; отсеивается только ЯВНАЯ склейка.
  // Отсеивается ЕДИНСТВЕННЫЙ бесспорный случай: склейка, сразу за которой
  // открывается скобка выражения. Подпись кнопки «+ Добавить концепцию»
  // тоже начинается со склейки — вторая редакция образца съела и её.
  // ЧИНЯ ПРИБОР, ПРОВЕРЯЙ НЕ ТОЛЬКО ТО, ЧТО УШЛО ЛИШНЕЕ, НО И ТО, ЧТО
  // ОСТАЛОСЬ НУЖНОЕ.
  const ОБРЫВОК = /^\+\s*\(/;
  const добавить = з => {
    const т = String(з).trim();
    if (!т || !/[А-Яа-яЁё]/.test(т) || данные.has(з)) return;
    if (ПРИЗНАКИ_КОДА.test(т) || ОБРЫВОК.test(т)) return;
    строки.add(т);
  };
  for (const м of текст.matchAll(/'([^'\n]*[А-Яа-яЁё][^'\n]*)'/g)) добавить(м[1]);
  for (const м of текст.matchAll(/"([^"\n]*[А-Яа-яЁё][^"\n]*)"/g)) добавить(м[1]);
  for (const м of текст.matchAll(/>\s*([^<>{}\n]*[А-Яа-яЁё][^<>{}\n]*?)\s*</g)) добавить(м[1]);
  const список = [...строки].sort();
  return { сколько: список.length, хеши: список.map(хеш), строки: список };
}

const текст = fs.readFileSync(ИСХОДНИК, 'utf8');
const нынешний = отпечатокСодержания(текст);
const режим = process.argv[2];

if (режим === 'учредить') {
  const правкаСодержания = process.argv.includes('--правка-содержания');
  if (fs.existsSync(ОТПЕЧАТОК) && !правкаСодержания) {
    console.error('Отпечаток уже есть. Учреждать заново можно ТОЛЬКО когда');
    console.error('содержание правили НАРОЧНО — тогда добавьте довод:');
    console.error('  node tools/content_probe.mjs учредить --правка-содержания');
    process.exit(1);
  }
  fs.mkdirSync(path.dirname(ОТПЕЧАТОК), { recursive: true });
  fs.writeFileSync(ОТПЕЧАТОК, JSON.stringify(
    { снят: new Date().toISOString().slice(0, 10), поля: нынешний }, null, 1));
  for (const [поле, о] of Object.entries(нынешний)) {
    console.log(`  ${поле.padEnd(22, '.')} ${о.сколько}`);
  }
  console.log('\nотпечаток содержания учреждён');
  process.exit(0);
}

if (!fs.existsSync(ОТПЕЧАТОК)) {
  console.error('Отпечатка нет. Учредите его, когда содержание заведомо цело:');
  console.error('  node tools/content_probe.mjs учредить');
  process.exit(1);
}

const был = JSON.parse(fs.readFileSync(ОТПЕЧАТОК, 'utf8')).поля;
let плохо = 0;

for (const поле of [...ПОЛЯ, 'ИНТЕРФЕЙС']) {
  if (поле === 'ИНТЕРФЕЙС') {
    const было = new Set(был.ИНТЕРФЕЙС?.строки ?? []);
    const стало = new Set(нынешний.ИНТЕРФЕЙС.строки);
    const пропали = [...было].filter(с => !стало.has(с));
    const появились = [...стало].filter(с => !было.has(с));
    if (!пропали.length && !появились.length) {
      console.log('  ИНТЕРФЕЙС'.padEnd(24, '.') + ' ' + стало.size);
    } else {
      плохо++;
      console.log(`✗ ИНТЕРФЕЙС: пропало ${пропали.length}, появилось ${появились.length}`);
      for (const с of пропали.slice(0, 5))   console.log('    − ' + с.slice(0, 88));
      for (const с of появились.slice(0, 5)) console.log('    + ' + с.slice(0, 88));
      const ещё = пропали.length + появились.length - 10;
      if (ещё > 0) console.log(`    … и ещё ${ещё}`);
    }
    continue;
  }
  const а = был[поле] ?? { сколько: 0, хеши: [] };
  const б = нынешний[поле];
  if (а.сколько !== б.сколько) {
    плохо++;
    console.log(`✗ ${поле}: было ${а.сколько}, стало ${б.сколько}`
      + (б.сколько < а.сколько ? ' — ЗНАЧЕНИЯ ПРОПАЛИ' : ' — значения прибавились'));
    continue;
  }
  const разошлись = [];
  for (let i = 0; i < а.хеши.length; i++) {
    if (а.хеши[i] !== б.хеши[i]) разошлись.push(i);
  }
  if (разошлись.length) {
    плохо++;
    console.log(`✗ ${поле}: изменено значений ${разошлись.length} из ${а.сколько}`);
    // Показываем НЫНЕШНИЙ вид первых расхождений: прежнего у нас нет и не
    // должно быть — хранится отпечаток, а не копия.
    const сейчас = собратьЗначения(текст)[поле];
    for (const i of разошлись.slice(0, 3)) {
      console.log(`    №${i}: ${String(сейчас[i]).slice(0, 90)}`);
    }
    if (разошлись.length > 3) console.log(`    … и ещё ${разошлись.length - 3}`);
  } else {
    console.log(`  ${поле.padEnd(22, '.')} ${а.сколько}`);
  }
}

if (плохо) {
  console.log('\n✗ СОДЕРЖАНИЕ ИЗМЕНИЛОСЬ. Если это была правка КОДА — вы задели');
  console.log('  текст и должны вернуть его. Если правка СОДЕРЖАНИЯ — учредите');
  console.log('  отпечаток заново: node tools/content_probe.mjs учредить --правка-содержания');
} else {
  console.log('\nсодержание не тронуто');
}
process.exit(плохо ? 1 : 0);
