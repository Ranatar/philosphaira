#!/usr/bin/env node
// ЧИСЛА В ДОКУМЕНТАЦИИ СВЕРЯЮТСЯ С ПРЕДМЕТОМ.
//
// Число, вписанное в текст на день написания, — отложенная поломка: оно
// живёт, пока кто-нибудь не поверит ему вместо карты. За август такое
// случалось трижды (проба откатывала «пять миграций», когда их стало
// девять; readme обещал 115 модулей при 124; 49 программ при 51), и всякий
// раз ловилось случайно.
//
// Здесь читается readme и сверяется с картами и деревом. Прибор не правит
// текст — он говорит, где текст разошёлся с предметом.
//
//   node tools/doc_numbers.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const readme = fs.readFileSync(path.join(КОРЕНЬ, 'readme.md'), 'utf8');
const дерево = JSON.parse(fs.readFileSync(path.join(КОРЕНЬ, 'mapping/map_tree.json'), 'utf8'));

const счёт = папка => fs.readdirSync(path.join(КОРЕНЬ, папка)).length;
const программ = fs.readdirSync(path.join(КОРЕНЬ, 'tools'))
  .filter(и => /\.(mjs|py|sh)$/.test(и)).length;
const эталонов = fs.readdirSync(path.join(КОРЕНЬ, 'baseline'))
  .filter(и => и.endsWith('.json') && и !== 'manifest.json').length;
const главСтилей = fs.readdirSync(path.join(КОРЕНЬ, 'app/css'))
  .filter(и => и.endsWith('.css')).length;

const проверки = [];
const п = (имя, было, стало) =>
  проверки.push({ имя, годно: было === стало, ждали: стало, вышло: было });

// Что ищем в тексте и с чем сверяем.
const найти = (образец, чтоЗначит) => {
  const м = readme.match(образец);
  if (!м) return { нет: true, чтоЗначит };
  return { число: Number(м[1]), чтоЗначит };
};

const сверки = [
  [/`app\/` \| (\d+) модул/,            дерево.меры.модулей,  'модулей в дереве'],
  [/Сборка — это `app\/`: \*\*(\d+) модул/, дерево.меры.модулей, 'модулей в дереве (§2)'],
  [/### `tools\/` — (\d+) программ/,    программ,             'программ в tools/'],
  [/`baseline\/` \| (\S+) заморож/,     null,                 'эталонов (словом)'],
];

for (const [образец, ждём, зачем] of сверки) {
  if (ждём === null) continue;
  const н = найти(образец, зачем);
  if (н.нет) { проверки.push({ имя: зачем, годно: false, ждали: ждём, вышло: 'НЕ НАЙДЕНО В ТЕКСТЕ' }); continue; }
  п(зачем, н.число, ждём);
}

// Главы стилей названы словом («в одиннадцати главах») — сверяем по счёту.
const словом = ['нуля','одной','двух','трёх','четырёх','пяти','шести','семи',
                'восьми','девяти','десяти','одиннадцати','двенадцати'];
const мГлав = readme.match(/стили в (\S+) глав/);
п('глав стилей (словом)', мГлав ? мГлав[1] : 'нет', словом[главСтилей]);

for (const з of проверки) {
  console.log((з.годно ? '  ' : '✗ ') + з.имя.padEnd(34, '.') +
    (з.годно ? '' : ` в тексте ${з.вышло}, на деле ${з.ждали}`));
}
const плохо = проверки.filter(з => !з.годно).length;
console.log(`\nсверок ${проверки.length}, разошлось ${плохо}`);
process.exit(плохо ? 1 : 0);
