#!/usr/bin/env node
// ПРОБНЫЙ ПРИБОР ДЛЯ Д2: чем платит и что даёт каждый облик поля traditions.
//
// Задача Д2 — развести в поле `traditions` то, что сейчас в нём смешано:
// период, школу и способ. Отчёт предлагает два поля (эпоха и школа) и
// пересечение по школе. Замер показал, что это чинит одно и ломает другое:
// Кант с Локком перестают быть «своими» (верно — общего у них только
// Просвещение), но и ПЛАТОН С АРИСТОТЕЛЕМ перестают (неверно — назвать их
// отношение межтрадиционным наравне с Кантом и Гуссерлем нельзя).
//
// Значит выбирать надо не «на что делить», а НА ЧТО ОТВЕЧАЕТ МЕРА БЛИЗОСТИ.
// Прибор ничего не решает: он считает последствия каждого облика на нынешних
// данных, чтобы решение принималось по числам.
//
// ПРИБОР НЕ ПЕРЕСКАЗЫВАЕТ ЛОГИКУ ПРИЛОЖЕНИЯ. Он подменяет поле traditions в
// живой странице и переспрашивает СОБСТВЕННЫЕ функции приложения —
// traditionBridgingIndex, sameTraditionPhil, philosopherSimilarity. Иначе
// вышел бы пятый случай пересказа: правило, записанное дважды, расходится с
// первой же правкой (см. doc/build-ops.md).
//
// Подмена возможна потому, что замерено: мостовость читает
// `_philosopherMap.get(id).traditions` НАПРЯМУЮ и своего кеша не имеет, а
// профиль метрик от традиций не зависит вовсе (ни одна из семнадцати метрик
// не зовёт sameTraditionPhil при взгляде «вся»).
//
//   node tools/tradition_trial.mjs [страница]
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { БРАУЗЕР, PUPPETEER, КОРЕНЬ, СЕРВЕР } from './paths.mjs';
const require = createRequire(import.meta.url);
const puppeteer = require(PUPPETEER);

const страница = process.argv[2] || 'index.html';
const РАЗМЕТКА = path.join(КОРЕНЬ, 'decisions', 'tradition_kinds.draft.json');

const разметка = JSON.parse(fs.readFileSync(РАЗМЕТКА, 'utf8'));
const видОф = {};
for (const [k, v] of Object.entries(разметка)) {
  if (k.startsWith('_')) continue;
  видОф[k] = v.измерение;
}
const спорные = Object.entries(разметка)
  .filter(([k, v]) => !k.startsWith('_') && v.спорно)
  .map(([k]) => k);

// ── облики ──────────────────────────────────────────────────────────
// Каждый облик — ПРОЕКЦИЯ разметки на нынешнее единственное поле. Так можно
// померить последствия, ничего не меняя в схеме данных: если облик выберут,
// поле разделится, а пока — просто оставляем в нём нужные измерения.
const ОБЛИКИ = [
  { имя: 'как сейчас', берём: null,
    что: 'всё вместе: период, школа и способ в одном поле' },
  { имя: 'только школа', берём: ['школа'],
    что: 'предложение Д2: пересечение считается по школе' },
  { имя: 'школа и метод', берём: ['школа', 'метод'],
    что: 'эпоха убрана, способ оставлен: Локк и Милль свои через века' },
  { имя: 'только эпоха', берём: ['эпоха'],
    что: 'для сравнения: во что превращается мера, если оставить один период' },
  { имя: 'школа, метод, эпоха порознь', берём: ['школа', 'метод'], порознь: true,
    что: 'то же, что «школа и метод», но эпоха считается ОТДЕЛЬНОЙ мерой близости' },
];

const В_БРАУЗЕРЕ = async (видОф, облики) => {
  const A = window.__app;
  // МОСТОВОСТЬ живёт в пространстве MET, а sameTraditionPhil своим модулем не
  // вывозится — оснастка отдаёт пространства целиком, и брать их надо оттуда,
  // а не дописывать в список имён то, чего модуль не вывозит.
  const мост = A.MET.traditionBridgingIndex;
  // Признак «свои» приложение прячет; но он в точности «есть общая традиция»,
  // и это ЕДИНСТВЕННОЕ место, где прибор вынужден повторить приложение.
  // Отмечено намеренно: если правило усложнится, здесь разойдётся первым.
  const свои = (a, b) => {
    if (a === b) return true;
    const ta = (проекция.get(a) || {}).traditions || [];
    const tb = (проекция.get(b) || {}).traditions || [];
    return ta.some(x => tb.includes(x));
  };
  const философы = A.DATA.philosophers;
  const исходные = new Map(философы.map(p => [p.id, (p.traditions || []).slice()]));
  if (!A.S._philosopherMap) A.initializePhilosophyMetrics();
  // КЛЮЧ ПРОЕКЦИИ — НЕ id, А ИМЯ. initializePhilosophyMetrics строит записи
  // как { id: philData.nameRu, ... }, и именно этим ключом концепции
  // ссылаются на автора (c.philosopher === 'Пифагор', не 'pythagoras').
  // Первая редакция прибора считала «своих» по id — и получала ноль пар при
  // любом облике. Ложное согласие второго рода: не «ничего не изменилось»,
  // а «изменилось всё до нуля», и заметно оно лишь потому, что прежняя
  // редакция давала 99 пар и число вдруг пропало.
  const ids = [...A.S._philosopherMap.keys()];
  const концепцииОф = new Map();
  for (const c of A.DATA.concepts) {
    if (!c.philosopher) continue;
    if (!концепцииОф.has(c.philosopher)) концепцииОф.set(c.philosopher, []);
    концепцииОф.get(c.philosopher).push(c.id);
  }

  // ПОДМЕНЯЕТСЯ ПРОЕКЦИЯ, А НЕ ЖИВЫЕ ЗАПИСИ. Первая редакция правила
  // A.DATA.philosophers — и мостовость не двигалась ни на десятую даже при
  // обнулении традиций у ВСЕХ. Причина записана в самом коде приложения:
  // «метрики работают не на живых записях, а на ПРОЕКЦИИ», которую строит
  // initializePhilosophyMetrics и держит в S._philosopherMap. Прибор,
  // меняющий не то, что читает проверяемый, показывает согласие всегда —
  // и это ровно та ошибка, что уже стоила нам подлога в blind_probe.
  const проекция = A.S._philosopherMap;
  const исходныеП = new Map([...проекция.entries()].map(([k, v]) => [k, (v.traditions || []).slice()]));

  const применить = (берём) => {
    for (const [id, зап] of проекция) {
      const было = исходныеП.get(id) || [];
      зап.traditions = берём ? было.filter(t => берём.includes(видОф[t])) : было.slice();
    }
    for (const p of философы) {
      const было = исходные.get(p.id) || [];
      p.traditions = берём ? было.filter(t => берём.includes(видОф[t])) : было.slice();
    }
  };

  const итог = [];
  for (const о of облики) {
    применить(о.берём);

    // ── пары философов «свои» — спрашиваем у приложения ──────────
    let своих = 0, всего = 0, безТрадиций = 0;
    const пары = [];
    for (let i = 0; i < ids.length; i++) {
      if (!((проекция.get(ids[i]) || {}).traditions || []).length) безТрадиций++;
      for (let j = i + 1; j < ids.length; j++) {
        всего++;
        const свои_ = свои(ids[i], ids[j]);
        if (свои_) { своих++; пары.push(ids[i] + '|' + ids[j]); }
      }
    }

    // ── мостовость — тоже спрашиваем ─────────────────────────────
    let суммаМост = 0, сНенулевой = 0, суммаПересечений = 0, достигнутоТрадиций = 0;
    for (const c of A.DATA.concepts) {
      const м = мост(c.id);
      if (!м) continue;
      суммаМост += м.total || 0;
      if ((м.total || 0) > 0) сНенулевой++;
      суммаПересечений += м.crossingLinks || 0;
      достигнутоТрадиций += м.traditionsReached || 0;
    }

    // ── философское сходство: доля межтрадиционных в верхних пятёрках ──
    let межтрад = 0, всегоПар = 0;
    try {
      const P = A.philosopherSimilarityData ? A.philosopherSimilarityData() : null;
      if (P) {
        for (let i = 0; i < ids.length; i++) {
          const зн = [];
          for (let j = 0; j < ids.length; j++) {
            if (i === j) continue;
            const v = A.philosopherSimilarity(ids[i], ids[j], 'rubrics');
            if (v > 0) зн.push([v, ids[j]]);
          }
          зн.sort((a, b) => b[0] - a[0]);
          for (const [, b] of зн.slice(0, 5)) {
            всегоПар++;
            if (!свои(ids[i], b)) межтрад++;
          }
        }
      }
    } catch (e) { /* мера может быть недоступна — не беда, поле останется пустым */ }

    итог.push({
      облик: о.имя, что: о.что,
      парСвоих: своих, парВсего: всего,
      философовБезТрадиций: безТрадиций,
      мостовость: { сумма: +суммаМост.toFixed(1), концепцийСНенулевой: сНенулевой,
                    пересечений: суммаПересечений, достигнутоТрадиций },
      рубрики: всегоПар ? { межтрадиционных: межтрад, из: всегоПар,
                            доля: +(межтрад / всегоПар).toFixed(3) } : null,
      _пары: пары,
    });
  }
  применить(null);          // вернуть как было
  return итог;
};

const browser = await puppeteer.launch({
  executablePath: БРАУЗЕР, headless: 'new',
  args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu'],
});
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 900 });
const ошибки = [];
page.on('pageerror', e => ошибки.push(String(e).split('\n')[0]));
await page.goto(СЕРВЕР + страница, { waitUntil: 'domcontentloaded', timeout: 60000 });
await new Promise(r => setTimeout(r, 4000));
if (страница.startsWith('_ref')) {
  await page.evaluate(() => { window.__app = window; window.__appReady = true; });
} else {
  await page.addScriptTag({ type: 'module', content: "import './_probe-rig.js';" });
  await page.waitForFunction('window.__appReady === true', { timeout: 20000 });
}
await new Promise(r => setTimeout(r, 1500));

const итог = await page.evaluate(В_БРАУЗЕРЕ, видОф, ОБЛИКИ);
await browser.close();

// ── отчёт ───────────────────────────────────────────────────────────
console.log(`\nПРОБА ОБЛИКОВ ПОЛЯ traditions — ${страница}; ошибок страницы ${ошибки.length}`);
if (спорные.length)
  console.log(`разметка ЧЕРНОВАЯ; спорных традиций ${спорные.length}: ${спорные.join(', ')}\n`);

for (const з of итог) {
  console.log(`── ${з.облик}`);
  console.log(`   ${з.что}`);
  console.log(`   пар «свои»: ${з.парСвоих} из ${з.парВсего}` +
    (з.философовБезТрадиций ? `; философов вовсе без традиций: ${з.философовБезТрадиций}` : ''));
  const м = з.мостовость;
  console.log(`   мостовость: сумма ${м.сумма}, концепций с ненулевой ${м.концепцийСНенулевой},` +
    ` пересечений ${м.пересечений}, достигнуто традиций ${м.достигнутоТрадиций}`);
  if (з.рубрики)
    console.log(`   сходство по рубрикам: межтрадиционных ${з.рубрики.межтрадиционных}` +
      ` из ${з.рубрики.из} = ${(з.рубрики.доля * 100).toFixed(1)} %`);
  console.log('');
}

// что переезжает между обликами
const базовые = new Set(итог[0]._пары);
for (const з of итог.slice(1)) {
  const свои = new Set(з._пары);
  const ушли = [...базовые].filter(p => !свои.has(p));
  const пришли = [...свои].filter(p => !базовые.has(p));
  console.log(`\n«${з.облик}» против «как сейчас»: перестали быть своими ${ушли.length},` +
    ` стали своими ${пришли.length}`);
  // Числа сами по себе не позволяют выбрать облик: 31 пара «перестала быть
  // своей» — это хорошо или плохо? Ответ виден только в именах. Поэтому
  // перечисляем — суждение о том, верно ли развести Платона с Аристотелем,
  // человеческое, и принимать его надо, глядя на пары, а не на счёт.
  const назвать = п => п.map(x => x.split('|').join(' ~ ')).sort();
  for (const п of назвать(ушли).slice(0, 40)) console.log('   − ' + п);
  if (ушли.length > 40) console.log(`   … и ещё ${ушли.length - 40}`);
  for (const п of назвать(пришли).slice(0, 20)) console.log('   + ' + п);
}
process.exit(ошибки.length ? 1 : 0);
