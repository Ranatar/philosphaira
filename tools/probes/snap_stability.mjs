#!/usr/bin/env node
// ПОВТОРИМОСТЬ ПОЛЕЙ СНИМКА. Прибор о приборе.
//
// За август sweep_all правился ЧЕТЫРЕЖДЫ, и каждый раз одной и той же
// болезнью в новом поле: снимок заставал состояние, которое ещё не устоялось,
// и величина гуляла от прогона к прогону. Ловилось это случайно — тем, что
// два прогона однажды не сошлись.
//
// Ждать пятого случая незачем. Эта проба спрашивает КАЖДОЕ поле снимка:
// повторяется ли оно, если снять его несколько раз в одном и том же
// состоянии. Поле, которое не повторяется, негодно как мера — и лучше
// узнать об этом здесь, чем через месяц на переучреждении эталона.
//
// ЧЕГО ЭТА ПРОБА НЕ ЛОВИТ — сказано здесь нарочно, чтобы она однажды не
// успокоила вместо того, чтобы предупредить.
//
// Она спрашивает: дрожит ли поле САМО ПО СЕБЕ в НАЗВАННОМ состоянии
// (анимация, таймер, случайность). Это настоящий класс, и на нём она зелёная.
//
// Но четыре случая августа были ДРУГИМ классом: поле не дрожало — обход
// приводил страницу к РАЗНЫМ состояниям, потому что успевал нажать разное
// число обработчиков (28 против 27 в видах статистики). Снимок честно
// отражал то, что видел; расходилось то, что он видел. Проба этого не
// увидит: состояние ей называют, а обходу — нет.
//
// Прибором для того класса остаётся СРАВНЕНИЕ ДВУХ ПРОГОНОВ одной стороны,
// а лечением — приведение состояния к названному перед каждым снимком.
// Проверено подлогом: если вернуть обходу прежнее поведение, эта проба
// останется зелёной, а сравнение двух прогонов покраснеет.
//
//   node tools/probes/snap_stability.mjs [index.html] [сколько_снимков] [зазор_мс]

import puppeteer from 'puppeteer-core';
import { PUPPETEER, БРАУЗЕР, СЕРВЕР, программа } from '../paths.mjs';
import { ХЕШ } from './snapshot.mjs';
import fs from 'node:fs';
import path from 'node:path';

const страница = process.argv[2] || 'index.html';
const РАЗ = Number(process.argv[3] || 5);
// Зазор между снимками мал НАРОЧНО: болезнь в том и состоит, что состояние
// доходит до места уже после снимка. Большой зазор её усыпляет.
const ЗАЗОР = Number(process.argv[4] || 60);
// Путь к обходу — у таблицы РАЗМЕЩЕНИЕ, а не «рядом со мной»: после
// разнесения по подпапкам соседство перестало быть надёжным признаком.

// Определение снимка берём из самого sweep_all: две копии разошлись бы
// молча, а прибор о приборе обязан мерить то же, что мерит прибор.
const исходникОбхода = fs.readFileSync(программа('sweep_all.mjs'), 'utf8');
const начало = исходникОбхода.indexOf('window.__snap = function () {');
const конец  = исходникОбхода.indexOf('};', исходникОбхода.indexOf("].join('|');"));
if (начало === -1 || конец === -1) {
  console.error('не нашёл определения __snap в sweep_all.mjs — прибор о приборе ' +
                'обязан брать его оттуда, а не хранить копию');
  process.exit(1);
}
const ОПРЕДЕЛЕНИЕ = исходникОбхода.slice(начало, конец + 2);

const ИМЕНА_ПОЛЕЙ = [
  'легенда', 'поиск пути', 'панель управления', 'кнопки входа',
  'облик вида статистики', 'окно универсальное', 'профиль концепции',
  'профиль философа', 'описания пути', 'окно входа',
  'видимость: статистика', 'видимость: универсальное', 'видимость: профиль концепции',
  'видимость: профиль философа', 'видимость: описания пути', 'видимость: подложка',
  'прозрачность подсказки', 'отмечено философов', 'отмечено связей',
  'отмечено рубрик', 'отмечено традиций', 'строка «Показано»', 'режим отбора',
];

const browser = await puppeteer.launch({
  executablePath: БРАУЗЕР, headless: 'new',
  args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu'],
});
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 900 });
await page.goto(СЕРВЕР + страница, { waitUntil: 'domcontentloaded' });
if (страница === 'index.html') {
  await page.addScriptTag({ type: 'module', content: "import './_probe-rig.js';" });
}
const ждать = мс => new Promise(r => setTimeout(r, мс));
await ждать(9000);
// __snap опирается на window.__hash — тот же, что ставит обход.
await page.evaluate(`window.__hash = (${ХЕШ});`);
await page.evaluate(ОПРЕДЕЛЕНИЕ);

const зов = страница === 'index.html' ? 'window.__app' : 'window';

// Состояния, в которых снимок бывает в обходе. В каждом — несколько снимков
// подряд БЕЗ единого действия между ними: всё, что при этом меняется,
// меняется само.
const состояния = [
  ['главная', async () => {}],
  ['окно статистики', async () => { await page.evaluate(`${зов}.openStatsModal()`); await ждать(800); }],
  ['вид betweenness', async () => { await page.evaluate(`${зов}.switchStatsView('betweenness')`); await ждать(1200); }],
  ['после счёта метрики', async () => {
    await page.evaluate(`(function(){
      var b = Array.from(document.querySelectorAll('#statsContentArea button'))
                .filter(function(x){ return /Рассчит/i.test(x.textContent); });
      if (b.length) b[0].click();
    })()`);
    await ждать(4000);
  }],
  // НАРОЧНО ТОРОПИМСЯ. Именно так обход и заставал подложку: окно
  // захлопывалось нажатием, ensureStats открывал его заново, и снимок
  // случался раньше, чем подложка успевала стать видимой. Состояние,
  // снятое с запасом времени, скрыло бы ровно ту болезнь, ради которой
  // проба и написана.
  ['окно закрыто и открыто наспех', async () => {
    await page.evaluate(`${зов}.closeStatsModal && ${зов}.closeStatsModal()`);
    await ждать(120);
    await page.evaluate(`${зов}.openStatsModal()`);
    await ждать(0);
  }],
  ['переключение видов подряд', async () => {
    for (const в of ['overview', 'pagerank', 'betweenness', 'critical-power']) {
      await page.evaluate(`${зов}.switchStatsView(${JSON.stringify(в)})`);
    }
    await ждать(0);
  }],
];

const шаткие = new Map();
for (const [имя, привести] of состояния) {
  await привести();
  const снимки = [];
  for (let i = 0; i < РАЗ; i++) {
    снимки.push(String(await page.evaluate('window.__snap()')).split('|'));
    await ждать(ЗАЗОР);
  }
  for (let п = 0; п < снимки[0].length; п++) {
    const значения = new Set(снимки.map(с => с[п]));
    if (значения.size > 1) {
      const ключ = ИМЕНА_ПОЛЕЙ[п] ?? `поле ${п + 1}`;
      if (!шаткие.has(ключ)) шаткие.set(ключ, []);
      шаткие.get(ключ).push(`${имя}: ${[...значения].map(v => v.slice(0, 24)).join(' / ')}`);
    }
  }
  console.log(`  ${имя.padEnd(32, '.')} снято ${РАЗ}, полей ${снимки[0].length}`);
}

console.log();
if (!шаткие.size) {
  console.log(`все ${ИМЕНА_ПОЛЕЙ.length} полей повторяются во всех состояниях`);
} else {
  for (const [поле, где] of шаткие) {
    console.log(`✗ ПОЛЕ «${поле}» НЕ ПОВТОРЯЕТСЯ`);
    for (const с of где) console.log(`    ${с}`);
  }
}
console.log(`\nполей ${ИМЕНА_ПОЛЕЙ.length}, шатких ${шаткие.size}`);
await browser.close();
process.exit(шаткие.size ? 1 : 0);
