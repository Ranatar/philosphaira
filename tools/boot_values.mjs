#!/usr/bin/env node
// ПРИЗНАК boot ПРОВЕРЯЕТСЯ ПРИБОРОМ, А НЕ ГЛАЗОМ.
//
// В теле boot() не должно оставаться ЗНАЧЕНИЙ: сборка соединяет части, а не
// вычисляет их. Всё, что можно вычислить в теле своего модуля, туда и уходит —
// за этим следит разбивка. Здесь мы лишь ловим возврат к прежнему: стоит
// правилу отложения огрубеть, как значения снова потекут в сборку, и заметить
// это по одному лишнему присваиванию среди семи десятков кусков нельзя.
//
// Что здесь НЕ считается значением:
//   S.simulation.on("tick", …)   — подписка на ход раскладки, это связывание;
//   S.x.метод(…) вообще          — обращение к уже готовому, а не вычисление.
// Считается значением только присваивание САМОЙ ячейке: `S.имя = …`.
//
//   node tools/boot_values.mjs [дерево]
import fs from 'node:fs';
import { ДЕРЕВО as ДЕРЕВО_ПО_УМОЛЧАНИЮ } from './paths.mjs';
import path from 'node:path';

const ДЕРЕВО = process.argv[2] || ДЕРЕВО_ПО_УМОЛЧАНИЮ;
const файл = path.join(ДЕРЕВО, 'boot.js');
if (!fs.existsSync(файл)) { console.error('нет ' + файл); process.exit(2); }

const текст = fs.readFileSync(файл, 'utf8');
const метка = 'export async function boot() {';
const i = текст.indexOf(метка);
if (i < 0) { console.error('в boot.js нет тела boot()'); process.exit(2); }
const тело = текст.slice(i + метка.length);

// присваивание самой ячейке: два пробела отступа, S.имя, затем `=` (но не `==`)
const рв = /^ {2}(S|DATA|MET|VIEWS)\.([A-Za-z_$][\w$]*)\s*=(?!=)/gm;
const найдено = [];
for (const m of тело.matchAll(рв)) найдено.push(`${m[1]}.${m[2]}`);

// счёт кусков и связывания — для картины, не для приговора
const строки = тело.split('\n').filter(с => с.trim());
const кусков = строки.filter(с => /^ {2}\S/.test(с)).length;

console.log(`boot(): кусков ${кусков}, строк ${строки.length}`);
if (найдено.length === 0) {
  console.log('значений в сборке: 0 — признак соблюдён');
  process.exit(0);
}
console.log(`ЗНАЧЕНИЙ В СБОРКЕ: ${найдено.length} — признак нарушен`);
for (const н of найдено) console.log('   ' + н);
console.log('\nЗначение в сборке означает, что его нельзя вычислить в теле своего');
console.log('модуля. Найдите причину: не готова ли к тому времени какая-то часть');
console.log('(данные, разметка, чужая ячейка, имя пространства) — и поставьте ввоз');
console.log('ради порядка вместо отложения. Порядок работ — в build-ops.md.');
process.exit(1);
