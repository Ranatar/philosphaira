#!/usr/bin/env node
// МЕРЫ РАСКЛАДКИ — прибор к силовой укладке.
//
// ЧЕГО ЭТОТ ПРИБОР НЕ ДЕЛАЕТ: он не сличает координаты. Замерено, что один
// и тот же d3 7.8.5 в Chrome и в node даёт РАЗНЫЕ раскладки на одних данных,
// одних параметрах и одном числе тиков (медиана расхождения 65 px, максимум
// 266): движки расходятся в последних битах, а Барнс–Хат это усиливает.
// Список одиноких узлов при этом совпадает на 27 из 40 — устойчиво явление,
// а не точка. Поэтому мерятся МЕРЫ.
//
// ПОЧЕМУ НАБОР, А НЕ ОДНА РАСКЛАДКА. На единственной раскладке тяга к центру
// выглядела выигрышем без платы (группировка традиций 0,584 против 0,630 —
// лучше базы). На десяти случайных стартах это не подтвердилось: попарно тяга
// хуже базы в десяти прогонах из десяти, а разброс между раскладками (±0,04)
// больше самой разницы (+0,023). По одной паре чисел ответить было нельзя
// в принципе.
//
// ЧТО МЕРЯЕТСЯ на каждом старте:
//   медиана расстояния до ближайшего соседа — 90 = два радиуса столкновения,
//     признак того, что ядро осталось заклиненной упаковкой;
//   одиноких — узлов дальше 150 px от ближайшего соседа;
//   отношение — среднее расстояние внутри традиции к среднему между
//     традициями: чем меньше, тем яснее раскладка разложила философию;
//   охват — наибольшая сторона облака.
//
// ЧЕГО ПРИБОР НЕ ПЕРЕНОСИТ: силу пружины. У d3 она по умолчанию считается
// из степеней концов, и её накопитель принадлежит ТОЙ симуляции, в которой
// связи были разложены; перенести accessor значит перенести чужие счётчики.
// Приложение эту силу не задаёт, так что обе стороны берут одно умолчание.
//
//   node tools/layout_probe.mjs [страница]        по умолчанию index.html
import { createRequire } from 'node:module';
import { PUPPETEER, БРАУЗЕР, СЕРВЕР } from './paths.mjs';
const require = createRequire(import.meta.url);
const puppeteer = require(PUPPETEER);

const СТРАНИЦА = process.argv[2] || 'index.html';
const ПРОГОНОВ = +(process.env.PG_LAYOUT_RUNS || 10);
const wait = ms => new Promise(r => setTimeout(r, ms));

// ── ожидаемое. Поля, а не точки: раскладка от старта к старту гуляет ──
// Числа сняты на этом же приборе; ширина полей взята с запасом в два-три
// стандартных отклонения от замеренного разброса.
const ЖДЁМ = {
  медиана: [88, 92],        // два радиуса столкновения (45 × 2)
  одиноких: [3, 16],        // без тяги было 17,3 ± 3,7; с тягой 9,8 ± 4,0
  отношение: [0.45, 0.65],  // замерено 0,574 ± 0,052
  охват: [2300, 3200],      // замерено 2961 ± 124; без тяги 3402 — вне поля
};

const проверки = [];
const проверить = (имя, годно, ждали, вышло) =>
  проверки.push({ имя, годно: !!годно, ждали, вышло });

const browser = await puppeteer.launch({
  executablePath: БРАУЗЕР, headless: 'new',
  args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu'],
});
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 900 });
const ошибки = [];
page.on('pageerror', e => ошибки.push(String(e).split('\n')[0]));
page.on('dialog', async d => { try { await d.accept(); } catch (e) {} });

await page.goto(СЕРВЕР + СТРАНИЦА, { waitUntil: 'domcontentloaded', timeout: 60000 });
await wait(6500);
const модуль = !СТРАНИЦА.startsWith('_ref');
await page.addScriptTag(модуль
  ? { type: 'module', content: `import './_probe-rig.js'; window.__t = window.__app; window.__tReady = true;` }
  : { content: `
      // У исходника верхнеуровневые let/const не попадают в window, но видны
      // через eval в глобальной области — та же прослойка, что в blind_probe.
      const взять = имя => { try { return eval(имя); } catch (e) { return undefined; } };
      window.__t = {
        DATA: { concepts: взять('concepts'), relations: взять('relations'),
                philosophers: взять('philosophers') },
        S: { simulation: взять('simulation'), maxTicks: взять('maxTicks') },
      };
      // Живой замер читает DATA.nodes; у исходника узлы зовутся просто nodes.
      window.__t.DATA.nodes = взять('nodes');
      window.__tReady = true;` });
await page.waitForFunction('window.__tReady === true', { timeout: 30000 });

// ЖИВАЯ РАСКЛАДКА СТРАНИЦЫ — отдельный и главный замер. Модель ниже строит
// раскладку сама и потому не видит того, что случилось с силами ПРИ
// ЗАПОМИНАНИИ: d3 обходит узлы один раз при initialize и складывает силы в
// массив. Спросить функцию силы позже — значит спросить не то, чем считали.
// Мина, на которой это выяснилось: тяга, поставленная до построения
// указателя связей, запоминалась ровной, а функция при опросе отвечала
// верно, и заслон по функции молчал.
const живая = await (async () => {
  let преж = null, тихо = 0, точки = null;
  for (let i = 0; i < 90 && !точки; i++) {
    const c = await page.evaluate(() => window.__t.DATA.nodes.map(n => [n.x, n.y]));
    if (преж) {
      let m = 0;
      for (let k = 0; k < c.length; k++)
        m = Math.max(m, Math.hypot(c[k][0] - преж[k][0], c[k][1] - преж[k][1]));
      if (m < 0.01) { if (++тихо >= 2) точки = c; } else тихо = 0;
    }
    преж = c;
    if (!точки) await wait(500);
  }
  точки = точки || преж;
  const бл = [];
  for (let i = 0; i < точки.length; i++) {
    let л = Infinity;
    for (let j = 0; j < точки.length; j++) {
      if (i === j) continue;
      const d2 = (точки[i][0] - точки[j][0]) ** 2 + (точки[i][1] - точки[j][1]) ** 2;
      if (d2 < л) л = d2;
    }
    бл.push(Math.sqrt(л));
  }
  бл.sort((a, b) => a - b);
  const xs = точки.map(p => p[0]), ys = точки.map(p => p[1]);
  return {
    медиана: бл[Math.floor(бл.length / 2)],
    одиноких: бл.filter(d => d > 150).length,
    охват: Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys)),
  };
})();

// Раскладки считаются вызовом sim.tick() при остановленной симуляции. Право
// на такую замену доказано сличением: ручной прогон совпал с живой страницей
// ПОБАЙТОВО (медиана и максимум расхождения 0.000). Считать в кадре нельзя —
// десять прогонов заняли бы четыре минуты вместо шести секунд.
const замер = await page.evaluate(async (ПРОГОНОВ) => {
  const D = window.__t.DATA, d3 = window.d3;
  const концепции = D.concepts, связи = D.relations, философы = D.philosophers;
  const традицияПо = {};
  философы.forEach(p => { традицияПо[p.id] = (p.traditions || ['?'])[0]; });
  const традКонцепции = концепции.map(c => традицияПо[c.philosopher] || '?');

  // СИЛЫ СПРАШИВАЮТСЯ У ЖИВОЙ СИМУЛЯЦИИ, а не переписываются числами.
  // Прибор, пересказывающий правило приложения, показывает полное согласие
  // при подложенной поломке — в этом проекте так уже случалось четырежды.
  const s0 = window.__t.S.simulation;
  const fl = s0.force('link'), ch = s0.force('charge'), co = s0.force('collision');
  const px = s0.force('pullX'), py = s0.force('pullY');
  const жив = {
    расстояние: fl.distance(),
    заряд: ch.strength(),
    столкновение: co.radius(),
    распад: s0.alphaDecay(),
    потолок: window.__t.S.maxTicks,
    тягаX: px ? px.strength() : null,
    тягаY: py ? py.strength() : null,
  };

  const итог = [];
  for (let s = 0; s < ПРОГОНОВ; s++) {
    let seed = 987654 + s * 4111;
    const rnd = () => (seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff;
    const nodes = концепции.map(c => {
      const r = 1400 * Math.sqrt(rnd()), a = 2 * Math.PI * rnd();
      return { id: c.id, x: 720 + r * Math.cos(a), y: 450 + r * Math.sin(a), vx: 0, vy: 0 };
    });
    const links = связи.map(r => ({ source: r.source, target: r.target }));
    const deg = {};
    nodes.forEach(n => { deg[n.id] = 0; });
    links.forEach(l => { if (l.source !== l.target) { deg[l.source]++; deg[l.target]++; } });
    const sim = d3.forceSimulation(nodes)
      .force('link', d3.forceLink(links).id(d => d.id).distance(жив.расстояние))
      .force('charge', d3.forceManyBody().strength(жив.заряд))
      .force('center', d3.forceCenter(720, 450))
      .force('collision', d3.forceCollide().radius(жив.столкновение))
      .alphaDecay(жив.распад).stop();
    // Тяга ставится ТОЛЬКО если она есть у живой симуляции, и с ЕЁ функцией
    // силы. Прибор не знает ни про 0.1, ни про «делить на степень» — он
    // спрашивает. Снимут тягу со страницы — прибор увидит это числом
    // одиноких, а не промолчит.
    if (жив.тягаX) sim.force('pullX', d3.forceX(720).strength(жив.тягаX));
    if (жив.тягаY) sim.force('pullY', d3.forceY(450).strength(жив.тягаY));
    sim.tick(жив.потолок);

    const X = nodes.map(n => [n.x, n.y]);
    const бл = [];
    let внутриСум = 0, внутриN = 0, междуСум = 0, междуN = 0;
    for (let i = 0; i < X.length; i++) {
      let лучш = Infinity;
      for (let j = 0; j < X.length; j++) {
        if (i === j) continue;
        const d2 = (X[i][0] - X[j][0]) ** 2 + (X[i][1] - X[j][1]) ** 2;
        if (d2 < лучш) лучш = d2;
        if (j > i) {
          const d = Math.sqrt(d2);
          if (традКонцепции[i] === традКонцепции[j]) { внутриСум += d; внутриN++; }
          else { междуСум += d; междуN++; }
        }
      }
      бл.push(Math.sqrt(лучш));
    }
    бл.sort((a, b) => a - b);
    const xs = X.map(p => p[0]), ys = X.map(p => p[1]);
    итог.push({
      медиана: бл[Math.floor(бл.length / 2)],
      одиноких: бл.filter(d => d > 150).length,
      отношение: (внутриСум / внутриN) / (междуСум / междуN),
      охват: Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys)),
    });
  }
  // Отчёт о снятых силах — чтобы подлог был виден не только числом мер.
  // Ускорители d3 отдают величину через accessor, поэтому спрашиваем их на
  // первой связи и первом узле последнего прогона.
  const образецУзла = { id: концепции[0].id }, образецСвязи = { source: концепции[0].id, target: концепции[1].id };
  const знач = (a, о) => (typeof a === 'function' ? a(о, 0, [о]) : a);
  return { итог, снятое: {
    расстояние: знач(жив.расстояние, образецСвязи),
    заряд: знач(жив.заряд, образецУзла),
    столкновение: знач(жив.столкновение, образецУзла),
    распад: жив.распад, потолок: жив.потолок, тягаЕсть: !!(жив.тягаX && жив.тягаY),
    // Спрашиваем силу у самого связного узла и у самого одинокого: у
    // обратной степени они обязаны различаться, у ровной — совпадут.
    тягаРазная: (() => {
      if (!жив.тягаX) return false;
      const ст = {};
      концепции.forEach(c => { ст[c.id] = 0; });
      связи.forEach(r => { if (r.source !== r.target) { ст[r.source]++; ст[r.target]++; } });
      const по = Object.keys(ст).sort((a, b) => ст[b] - ст[a]);
      const богатый = { id: по[0] }, бедный = { id: по[по.length - 1] };
      return жив.тягаX(богатый, 0, [богатый]) !== жив.тягаX(бедный, 0, [бедный]);
    })(),
  } };
}, ПРОГОНОВ);
const { итог: меры, снятое } = замер;

await page.close(); await browser.close();

console.log('силы, снятые с живой симуляции: расстояние ' + снятое.расстояние +
  ', заряд ' + снятое.заряд + ', столкновение ' + снятое.столкновение +
  ', распад ' + снятое.распад + ', потолок ' + снятое.потолок +
  ', тяга ' + (снятое.тягаЕсть ? 'есть' : 'НЕТ') + '\n');

const сред = к => меры.reduce((s, м) => s + м[к], 0) / меры.length;
const откл = к => {
  const m = сред(к);
  return Math.sqrt(меры.reduce((s, м) => s + (м[к] - m) ** 2, 0) / меры.length);
};

for (const [к, [низ, верх]] of Object.entries(ЖДЁМ)) {
  const m = сред(к), s = откл(к);
  проверить(`${к} в поле`, m >= низ && m <= верх, `${низ}…${верх}`,
    m.toFixed(к === 'отношение' ? 3 : 1) + ' ± ' + s.toFixed(к === 'отношение' ? 3 : 1));
}
// Устойчивость: если разброс одиноких вырос вдвое против замеренного, значит
// раскладка стала зависеть от начала сильнее, чем от данных.
проверить('разброс числа одиноких не вырос', откл('одиноких') < 8, '<8', откл('одиноких').toFixed(1));

// ЗАСЛОН ОТ МИНЫ, КОТОРАЯ УЖЕ СРАБАТЫВАЛА, — ПО ЖИВОЙ РАСКЛАДКЕ.
// Тяга, поставленная ДО построения указателя связей, запоминается ровной
// (0,1 у всех), и раскладка сжимается: охват 2248 против 2961, одиноких 0,8
// против 9,8. Замер до починки: стороны разошлись на 291 px по медиане.
// ПЕРВАЯ РЕДАКЦИЯ ЭТОГО ЗАСЛОНА БЫЛА ПУСТОЙ: она спрашивала функцию силы, а
// функция при позднем опросе отвечает верно — врал не она, а запомненный
// массив. Подлог прошёл незамеченным. Спрашивать надо СЛЕДСТВИЕ.
проверить('живая раскладка: охват в поле', живая.охват >= ЖДЁМ.охват[0] && живая.охват <= ЖДЁМ.охват[1],
  `${ЖДЁМ.охват[0]}…${ЖДЁМ.охват[1]}`, живая.охват.toFixed(0));
проверить('живая раскладка: одиноких в поле',
  живая.одиноких >= ЖДЁМ.одиноких[0] && живая.одиноких <= ЖДЁМ.одиноких[1] + 16,
  `${ЖДЁМ.одиноких[0]}…${ЖДЁМ.одиноких[1] + 16}`, живая.одиноких);
проверить('живая раскладка: ядро заклинено',
  живая.медиана >= ЖДЁМ.медиана[0] && живая.медиана <= ЖДЁМ.медиана[1],
  `${ЖДЁМ.медиана[0]}…${ЖДЁМ.медиана[1]}`, живая.медиана.toFixed(1));
проверить('ошибок страницы нет', ошибки.length === 0, 0,
  ошибки.length + (ошибки[0] ? ' (' + ошибки[0].slice(0, 60) + ')' : ''));

const плохо = проверки.filter(п => !п.годно);
for (const п of проверки)
  console.log(`${п.годно ? '✓' : '✗'} ${п.имя}: ждали ${п.ждали}, вышло ${п.вышло}`);
console.log(`\nпрогонов ${меры.length}, утверждений ${проверки.length}, не сошлось ${плохо.length}`);
process.exit(плохо.length ? 1 : 0);
