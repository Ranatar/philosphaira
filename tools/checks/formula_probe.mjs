#!/usr/bin/env node
// ЧЕСТНОСТЬ ВЕРСИЙ ФОРМУЛ (`formula_probe`).
//
// ЗАЧЕМ. Замер метрики без отметки о версии формулы — число без
// родословной. В формулах зашиты коэффициенты (`targetedPhilosophers * 0.8`,
// `incomingDevelopments * 0.5`, порог `0.3`); поправив 0.8 на 0.9 и не
// отметив этого, получим ряд замеров, который выглядит историей ГРАФА, а
// окажется историей наших правок КОДА. Это хуже отсутствия истории: ложная
// история убедительна.
//
// ПОЧЕМУ ПРИБОР, А НЕ ПРАВИЛО. Поднимать версию вручную забудут — не по
// небрежности, а потому что правка формулы обычно мелкая и делается заодно
// с другим. Прибор сверяет ОТПЕЧАТОК ТЕЛА функции с записанным при
// последней смене версии: изменил формулу, не поднял версию — приёмка
// краснеет и называет метрику поимённо.
//
//   node tools/checks/formula_probe.mjs                    # проверить
//   node tools/checks/formula_probe.mjs поднять <метрика>… # формула изменена нарочно
//
// ВЕРСИИ ЖИВУТ В ДВУХ МЕСТАХ, И ОБА ВЕДЁТ ЭТОТ ПРИБОР. Свод —
// `baseline/formulas.json`; страница — `const FORMULA_VERSIONS` в исходнике,
// ею подписывается каждый замер, уходящий на сервер (`formulaVersion` в
// `POST /api/metrics/observations`). Два списка руками — это однажды их
// разойти, и замер подпишется версией, которой формула не соответствует:
// ровно та ложь, ради предотвращения которой версии заведены. Поэтому
// `поднять` переписывает блок на странице заодно со сводом, а проверка
// сличает блок со сводом знак в знак. (До 2026-09-10 это делала отдельная
// программа sync_formula_versions.mjs, не входившая в приёмку.)
//
// ОТПЕЧАТОК БЕРЁТСЯ ОТ ТЕЛА БЕЗ ПОЯСНЕНИЙ И ЛИШНИХ ПРОБЕЛОВ: переписанный
// комментарий или перенос строки — не смена формулы, и краснеть на них
// значило бы приучить не читать прибор.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { ИСХОДНИК, КОРЕНЬ } from '../paths.mjs';

const СВОД = path.join(КОРЕНЬ, 'baseline', 'formulas.json');
const текст = fs.readFileSync(ИСХОДНИК, 'utf8');

/** Перечень метрик берётся из САМОГО исходника, а не из списка рядом:
 *  список рядом устареет молча, как только заведут новую метрику. */
function имёнаМетрик() {
  const н = текст.indexOf('const METRIC_FLAGS = {');
  if (н < 0) throw new Error('METRIC_FLAGS не найден — исходник другой редакции');
  const блок = текст.slice(н, текст.indexOf('\n    };', н));
  return [...блок.matchAll(/^\s+(\w+):\s*\{/gm)].map(м => м[1]);
}

function телоФункции(имя) {
  const н = текст.indexOf('function ' + имя);
  if (н < 0) return null;
  let глубина = 0;
  for (let j = текст.indexOf('{', н); j < текст.length; j++) {
    if (текст[j] === '{') глубина++;
    else if (текст[j] === '}' && --глубина === 0) return текст.slice(н, j + 1);
  }
  return null;
}

const отпечаток = тело => crypto.createHash('sha256').update(
  тело.replace(/\/\/[^\n]*/g, '').replace(/\/\*[\s\S]*?\*\//g, '')
      .replace(/\s+/g, ' ').trim()).digest('hex').slice(0, 16);

const метрики = имёнаМетрик();
const свод = JSON.parse(fs.readFileSync(СВОД, 'utf8'));
const режим = process.argv[2];

/** Блок FORMULA_VERSIONS на странице, каким он ОБЯЗАН быть по своду. */
const МЕТКА = 'const FORMULA_VERSIONS = Object.freeze({';
function блокНаСтранице() {
  const н = текст.indexOf(МЕТКА);
  if (н < 0) return null;
  const к = текст.indexOf('});', н) + 3;
  return { н, к, было: текст.slice(н, к) };
}
function блокПоСводу() {
  const строки = Object.entries(свод.формулы).sort()
    .map(([и, о]) => `      ${и}: ${о.версия}`).join(',\n');
  return `${МЕТКА}\n${строки}\n    });`;
}

if (режим === 'поднять') {
  const кого = process.argv.slice(3);
  if (!кого.length) {
    console.error('Назовите метрики: node tools/checks/formula_probe.mjs поднять calculatePageRank …');
    process.exit(1);
  }
  for (const имя of кого) {
    const тело = телоФункции(имя);
    if (!тело) { console.error(`✗ ${имя}: функции нет`); process.exit(1); }
    const было = свод.формулы[имя]?.версия ?? 0;
    свод.формулы[имя] = { версия: было + 1, отпечаток: отпечаток(тело) };
    console.log(`  ${имя}: версия ${было} → ${было + 1}`);
  }
  fs.writeFileSync(СВОД, JSON.stringify(свод, null, 1));
  const блок = блокНаСтранице();
  if (!блок) { console.error('✗ FORMULA_VERSIONS в исходнике нет — страница не подпишет замер'); process.exit(1); }
  fs.writeFileSync(ИСХОДНИК, текст.slice(0, блок.н) + блокПоСводу() + текст.slice(блок.к));
  console.log('  FORMULA_VERSIONS на странице переписан по своду; исходник изменён — пересоберите дерево');
  console.log('\nверсии подняты. ЗАМЕРЫ, СНЯТЫЕ ПРЕЖНЕЙ ФОРМУЛОЙ, СРАВНЕНИЮ');
  console.log('С НОВЫМИ НЕ ПОДЛЕЖАТ — это и есть смысл версии.');
  process.exit(0);
}

let плохо = 0;
const новые = метрики.filter(и => !(и in свод.формулы));
const пропавшие = Object.keys(свод.формулы).filter(и => !метрики.includes(и));

for (const имя of метрики) {
  const записано = свод.формулы[имя];
  if (!записано) continue;
  const тело = телоФункции(имя);
  if (!тело) {
    плохо++;
    console.log(`✗ ${имя}: в своде есть, а функции в исходнике нет`);
    continue;
  }
  if (отпечаток(тело) !== записано.отпечаток) {
    плохо++;
    console.log(`✗ ${имя}: ФОРМУЛА ИЗМЕНЕНА, а версия осталась ${записано.версия}`);
  }
}

if (новые.length) {
  плохо++;
  console.log(`✗ метрики без версии формулы (${новые.length}): ${новые.join(', ')}`);
  console.log('   заведите: node tools/checks/formula_probe.mjs поднять ' + новые.join(' '));
}
if (пропавшие.length) {
  плохо++;
  console.log(`✗ в своде есть, а в METRIC_FLAGS нет: ${пропавшие.join(', ')}`);
}
{
  const блок = блокНаСтранице();
  if (!блок) { плохо++; console.log('✗ FORMULA_VERSIONS на странице нет'); }
  else if (блок.было !== блокПоСводу()) {
    плохо++;
    console.log('✗ FORMULA_VERSIONS НА СТРАНИЦЕ РАЗОШЁЛСЯ СО СВОДОМ — замер подпишется не той версией');
    console.log('   переписать: node tools/checks/formula_probe.mjs поднять <метрика> (или свод в исходник руками)');
  }
}

if (плохо) {
  console.log('\n✗ ВЕРСИИ ФОРМУЛ ВРУТ. Если правка МЕНЯЕТ ЧИСЛА — поднимите версию');
  console.log('  (node tools/checks/formula_probe.mjs поднять <метрика>). Если не меняет —');
  console.log('  значит отпечаток задет чем-то ещё, и это стоит понять до приёмки.');
} else {
  console.log(`метрик ${метрики.length}, версии формул честны, страница согласна со сводом`);
}
process.exit(плохо ? 1 : 0);
