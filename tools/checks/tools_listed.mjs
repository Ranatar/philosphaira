#!/usr/bin/env node
// ПЕРЕЧЕНЬ ПРОГРАММ СХОДИТСЯ С ПАПКОЙ.
//
// Повод: я трижды сверял это на коленке — однострочником, искавшим имя файла
// В ОБРАТНЫХ КАВЫЧКАХ. Он трижды показывал «не упомянуты: accept.sh,
// deploy_check.sh», хотя обе описаны в readme прозой и целыми разделами.
// Ложная тревога, повторяющаяся из захода в заход, хуже отсутствующей
// проверки: к ней привыкают и перестают читать.
//
// Здесь имя ищется КАК ТЕКСТ, в любом обрамлении, и отдельно сверяется
// заявленное число. Два вопроса, а не один: «все ли описаны» и «то ли число
// названо» — раньше они смешивались, и число никто не проверял вовсе.
// 10 сентября 2026 сюда добавлен третий вопрос: СХОДИТСЯ ЛИ С ПАПКОЙ ТАБЛИЦА
// РАЗМЕЩЕНИЯ (tools/paths.mjs и близнец paths.py). Через неё программы зовут
// друг друга и её же спрашивает приёмка; таблица, разошедшаяся с папкой,
// молча уводит зов в несуществующий путь. Обход папки здесь ВГЛУБЬ — чтобы
// проверка пережила разнесение программ по подпапкам.
import fs from 'node:fs';
import path from 'node:path';
import { КОРЕНЬ, ПРОГРАММЫ, РАЗМЕЩЕНИЕ, программа } from '../paths.mjs';

const ПАПКА = ПРОГРАММЫ;
const текст = fs.readFileSync(path.join(КОРЕНЬ, 'readme.md'), 'utf8');

/** Имя → подпапка относительно tools/. Обход вглубь: сегодня плоско, завтра нет. */
const вПапке = new Map();
(function обойти(п, под = '') {
  for (const f of fs.readdirSync(п)) {
    const полный = path.join(п, f);
    if (fs.statSync(полный).isDirectory()) { обойти(полный, path.join(под, f)); continue; }
    if (/\.(mjs|py|sh)$/.test(f)) вПапке.set(f, под);
  }
})(ПАПКА);

const программы = [...вПапке.keys()].sort();

const проверки = [];
const проверить = (имя, годно, ждали, вышло) =>
  проверки.push({ имя, годно: !!годно, ждали, вышло });

const неописанные = программы.filter(f => !текст.includes(f));
проверить('все программы описаны в readme', неописанные.length === 0, 0,
  неописанные.length ? неописанные.join(', ') : 0);

// Заявленное число. Оно живёт в заголовке раздела и потому легко устаревает:
// программу добавляют, а заголовок правит кто-нибудь потом.
const м = текст.match(/### `tools\/` — (\d+) программ/);
проверить('в readme названо число программ', !!м, 'есть строка',
  м ? м[1] : 'нет строки «### `tools/` — N программ»');
if (м) {
  проверить('и оно сходится с папкой', Number(м[1]) === программы.length,
    программы.length, м[1]);
}

// Обратное направление: readme не должен ссылаться на программы, которых нет.
// Так в проекте однажды жили призраки persist.mjs и freeze.mjs.
const призраки = [...текст.matchAll(/`(tools\/)?([a-z_0-9]+\.(?:mjs|py|sh))`/g)]
  .map(x => x[2])
  .filter((имя, i, все) => все.indexOf(имя) === i)
  .filter(имя => !программы.includes(имя) && !fs.existsSync(path.join(КОРЕНЬ, 'server', 'scripts', имя))
                 && !fs.existsSync(path.join(КОРЕНЬ, 'server', 'probes', имя))
                 && !fs.existsSync(path.join(КОРЕНЬ, имя)));
проверить('призраков в readme нет', призраки.length === 0, 0,
  призраки.length ? призраки.join(', ') : 0);

// ── таблица размещения против папки, в обе стороны ────────────────────────
const внеТаблицы = программы.filter(и => РАЗМЕЩЕНИЕ[и] === undefined);
проверить('каждая программа папки есть в РАЗМЕЩЕНИИ', внеТаблицы.length === 0, 0,
  внеТаблицы.length ? внеТаблицы.join(', ') : 0);

const призракиТаблицы = Object.keys(РАЗМЕЩЕНИЕ).filter(и => !вПапке.has(и));
проверить('в РАЗМЕЩЕНИИ нет призраков', призракиТаблицы.length === 0, 0,
  призракиТаблицы.length ? призракиТаблицы.join(', ') : 0);

const неТам = программы.filter(и => РАЗМЕЩЕНИЕ[и] !== undefined
  && path.normalize(РАЗМЕЩЕНИЕ[и] || '.') !== path.normalize(вПапке.get(и) || '.'));
проверить('подпапка в таблице та же, что на деле', неТам.length === 0, 0,
  неТам.length ? неТам.map(и => `${и}: таблица «${РАЗМЕЩЕНИЕ[и]}», папка «${вПапке.get(и)}»`).join('; ') : 0);

// Путь, отданный таблицей, обязан существовать: иначе зов уйдёт в никуда.
const несуществующие = programsExist();
function programsExist() {
  return программы.filter(и => РАЗМЕЩЕНИЕ[и] !== undefined && !fs.existsSync(программа(и)));
}
проверить('путь от программа() ведёт к файлу', несуществующие.length === 0, 0,
  несуществующие.length ? несуществующие.join(', ') : 0);

// ── ПРИЗНАК ПАПКИ probes/ ПРОВЕРЯЕМ, А НЕ ВКУСОВОЙ ────────────────────────
// Программы разнесены 10 сентября 2026, и граница probes/ выбрана НЕ по теме
// («окна», «полотно», «стили» — деление вкусовое и разойдётся с делом при
// первом же новом приборе), а по тому, ЧЕМ прибор меряет: открывает ли он
// страницу браузером. Признак машинный — значит его можно стеречь.
//
// Правило одностороннее: браузерный обязан жить в probes/, но не всякий
// житель probes/ браузерный. Так, make_ref.py кладёт в дерево вторую сторону
// приёмки и сам браузера не открывает — он там потому, что нужен только
// браузерным приборам, и это решение человека, а не следствие признака.
//
// ЧЕСТНАЯ ОГОВОРКА, СДЕЛАННАЯ ПОСЛЕ ПОДЛОГА. Первая редакция этого
// утверждения была «браузерный ⇒ probes/» без исключений — и покраснела на
// живом дереве, назвав пять программ. Три названы по недосмотру (слово
// puppeteer стоит у них в пояснении или в имени переменной, а браузера они
// не открывают), и это чинится тем, что ищется ВВОЗ, а не слово. Но две
// оставшиеся показали, что признак не совпадает с ролью: layout.mjs считает
// раскладку В CHROME и вписывает координаты в исходник — это правка
// предмета, и место ей в edit/. Значит правило одностороннее и с одним
// ИМЕНОВАННЫМ исключением; безымянных быть не должно.
{
  const ВНЕ_PROBES = {
    'layout.mjs': 'считает раскладку в Chrome, но правит ИСХОДНИК — по роли это edit/',
  };
  // Образец собирается по кускам НАРОЧНО: иначе он находит сам себя — этот
  // файл содержит слова, которые ищет, и первая редакция назвала браузерным
  // прибор, ни разу не открывавший страницы.
  const ОБРАЗЕЦ = new RegExp('require\\(' + 'PUPPETEER' + '\\)|from ' + "'" + 'puppeteer');
  const ввозит = и => ОБРАЗЕЦ.test(fs.readFileSync(программа(и), 'utf8'));
  const браузерные = программы.filter(ввозит);
  const неТам = браузерные.filter(и => вПапке.get(и) !== 'probes' && !(и in ВНЕ_PROBES));
  проверить('браузерные приборы живут в probes/', неТам.length === 0, 0,
    неТам.length ? неТам.map(и => `${и} в «${вПапке.get(и) || 'корне'}»`).join(', ') : 0);
  // Исключение, переставшее быть исключением, — тоже расхождение: перечень
  // не должен пережить причину, по которой заведён.
  const лишние = Object.keys(ВНЕ_PROBES).filter(и => !браузерные.includes(и) || вПапке.get(и) === 'probes');
  проверить('в перечне исключений нет лишних', лишние.length === 0, 0,
    лишние.length ? лишние.join(', ') : 0);
}

// ── буквальные пути в подсказках и документах ведут к файлам ──────────────
// Программы советуют человеку следующий шаг строкой вида «дальше: node
// tools/remap.mjs собрать», и таких подсказок два десятка. После разнесения
// по подпапкам каждая станет враньём — молча, потому что подсказка не
// исполняется. Здесь всякий буквальный путь `tools/имя` проверяется на
// существование. doc/history.md исключён нарочно: это журнал, он говорит о
// прошлом, и переписывать его под нынешнюю раскладку значило бы подделать
// запись о том, что тогда делалось.
{
  const где = [];
  for (const и of программы) где.push([path.join(вПапке.get(и), и), fs.readFileSync(программа(и), 'utf8')]);
  for (const д of ['readme.md', 'doc/build.md', 'doc/build-ops.md', 'doc/module-ops.md'])
    где.push([д, fs.readFileSync(path.join(КОРЕНЬ, д), 'utf8')]);

  const плохие = [];
  for (const [чей, текстФайла] of где)
    for (const м of текстФайла.matchAll(/\btools\/([a-z_0-9/]+\.(?:mjs|py|sh))/g))
      if (!fs.existsSync(path.join(КОРЕНЬ, 'tools', м[1]))) плохие.push(`${чей} → tools/${м[1]}`);
  проверить('буквальные пути tools/… ведут к файлам', плохие.length === 0, 0,
    плохие.length ? [...new Set(плохие)].slice(0, 5).join('; ') : 0);
}

// ── близнец на python не разошёлся ────────────────────────────────────────
// Две таблицы вместо одной — сознательная цена двуязычной оснастки (см.
// paths.py). Цена терпима ровно потому, что расхождение ловится здесь.
{
  const питон = fs.readFileSync(path.join(ПАПКА, 'paths.py'), 'utf8');
  const блок = питон.slice(питон.indexOf('РАЗМЕЩЕНИЕ = {'), питон.indexOf('\n}', питон.indexOf('РАЗМЕЩЕНИЕ = {')));
  const близнец = Object.fromEntries([...блок.matchAll(/'([^']+)':\s*'([^']*)'/g)].map(м => [м[1], м[2]]));
  const разошлись = [...new Set([...Object.keys(РАЗМЕЩЕНИЕ), ...Object.keys(близнец)])]
    .filter(и => (РАЗМЕЩЕНИЕ[и] ?? null) !== (близнец[и] ?? null));
  проверить('таблицы paths.mjs и paths.py совпадают', разошлись.length === 0, 0,
    разошлись.length ? разошлись.join(', ') : 0);
}

for (const п of проверки)
  console.log(`${п.годно ? '✓' : '✗'} ${п.имя}: ждали ${п.ждали}, вышло ${п.вышло}`);
const плохо = проверки.filter(п => !п.годно);
console.log(`\nпрограмм ${программы.length}, утверждений ${проверки.length}, не сошлось ${плохо.length}`);
process.exit(плохо.length ? 1 : 0);
