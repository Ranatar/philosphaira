#!/usr/bin/env node
// ЧИСЛА В ДОКУМЕНТАЦИИ СВЕРЯЮТСЯ С ПРЕДМЕТОМ.
//
// Число, вписанное в текст на день написания, — отложенная поломка: оно
// живёт, пока кто-нибудь не поверит ему вместо карты. За август такое
// случалось трижды (проба откатывала «пять миграций», когда их стало
// девять; readme обещал 115 модулей при 124; 49 программ при 51), и всякий
// раз ловилось случайно.
//
// Здесь читается readme и сверяется с картами и деревом. Прибор не правит
// текст — он говорит, где текст разошёлся с предметом.
//
//   node tools/checks/doc_numbers.mjs

import fs from 'node:fs';
import path from 'node:path';
import { КОРЕНЬ } from '../paths.mjs';

// КОРЕНЬ спрашивается у paths.mjs, а не считается своим счётом: после
// разнесения программ по подпапкам (10 сентября 2026) «папка выше моей» —
// это уже tools/, а не корень проекта. Место, знающее раскладку, одно.
const readme = fs.readFileSync(path.join(КОРЕНЬ, 'readme.md'), 'utf8');
const дерево = JSON.parse(fs.readFileSync(path.join(КОРЕНЬ, 'mapping/map_tree.json'), 'utf8'));

const счёт = папка => fs.readdirSync(path.join(КОРЕНЬ, папка)).length;
// Счёт ВГЛУБЬ: программы разнесены по подпапкам (build/, maps/, edit/,
// probes/, checks/), и readdir по верхнему уровню считал бы девять из 61.
const программ = (function счёт(п) {
  let n = 0;
  for (const и of fs.readdirSync(п)) {
    const полный = path.join(п, и);
    if (fs.statSync(полный).isDirectory()) n += счёт(полный);
    else if (/\.(mjs|py|sh)$/.test(и)) n++;
  }
  return n;
})(path.join(КОРЕНЬ, 'tools'));
const эталонов = fs.readdirSync(path.join(КОРЕНЬ, 'baseline'))
  .filter(и => и.endsWith('.json') && и !== 'manifest.json').length;
const главСтилей = fs.readdirSync(path.join(КОРЕНЬ, 'app/css'))
  .filter(и => и.endsWith('.css')).length;
// Добавлено 10 сентября 2026 — после того как аудит нашёл в readme четыре
// числа, разошедшихся с предметом мимо этого прибора: строк исходника
// (31 404 при 42 401), имён в раскладке (764 при 887), связей (2169 при
// 2201), снимков обхода (297 при 315). Прибор на четыре сверки был прибором
// на четыре числа, а не на «числа в документации».
const читать = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const строкИсходника = читать('source/philosophy_graph_v3.html').split('\n').length - 1;
const раскладка = JSON.parse(читать('decisions/assign_names.json'));
const имёнВРаскладке = Object.keys(раскладка.по_имени).length;
const операторов = Object.keys(раскладка.операторы).length;
const снимковОбхода = JSON.parse(читать('baseline/manifest.json')).sweep_all.снимков;
const данных = н => JSON.parse(читать(`app/data/${н}.json`)).length;
const число = с => Number(String(с).replace(/\s/g, ''));

const проверки = [];
const п = (имя, было, стало) =>
  проверки.push({ имя, годно: было === стало, ждали: стало, вышло: было });

// Что ищем в тексте и с чем сверяем.
const найти = (образец, чтоЗначит) => {
  const м = readme.match(образец);
  if (!м) return { нет: true, чтоЗначит };
  return { число: число(м[1]), чтоЗначит };
};

const сверки = [
  [/`app\/` \| (\d+) модул/,            дерево.меры.модулей,  'модулей в дереве'],
  [/Сборка — это `app\/`: \*\*(\d+) модул/, дерево.меры.модулей, 'модулей в дереве (§2)'],
  [/### `tools\/` — (\d+) программ/,    программ,             'программ в tools/'],
  [/`baseline\/` \| (\S+) заморож/,     null,                 'эталонов (словом)'],
  [/одностраничный файл, ([\d ]+) строк/, строкИсходника,      'строк в исходнике (§1)'],
  [/`decisions\/assign_names\.json`: (\d+) им/, имёнВРаскладке, 'имён в раскладке (§4)'],
  [/раскладка: (\d+) имён и \d+ оператор/, имёнВРаскладке,   'имён в раскладке (§12)'],
  [/раскладка: \d+ имён и (\d+) оператор/, операторов,        'операторов в раскладке (§12)'],
  [/размещение (\d+) имён/,              имёнВРаскладке,       'имён в раскладке (§15)'],
  [/`sweep_all\.mjs` \| [^|]+\| (\d+) \|/, снимковОбхода,     'снимков обхода (§6)'],
  [/^Граф философских концепций: (\d+) концепций/m, данных('concepts'), 'концепций (шапка)'],
  [/^Граф философских концепций: \d+ концепций, (\d+) связей/m, данных('relations'), 'связей (шапка)'],
  [/^Граф философских концепций: \d+ концепций, \d+ связей, (\d+) философов/m, данных('philosophers'), 'философов (шапка)'],
  [/концепций, (\d+) связей,\n(\d+) философов, (\d+) традиций, (\d+) рубрик, (\d+) тип/, данных('relations'), 'связей (§1)'],
];

{
  const м = readme.match(/концепций, (\d+) связей,\n(\d+) философов, (\d+) традиций, (\d+) рубрик, (\d+) тип/);
  if (м) {
    п('философов (§1)', Number(м[2]), данных('philosophers'));
    п('традиций (§1)', Number(м[3]), данных('traditions'));
    п('рубрик (§1)', Number(м[4]), данных('rubrics'));
    п('типов связей (§1)', Number(м[5]), данных('relationTypes'));
  } else проверки.push({ имя: 'состав базы (§1)', годно: false, ждали: 'строка', вышло: 'НЕ НАЙДЕНО В ТЕКСТЕ' });
}
for (const [образец, ждём, зачем] of сверки) {
  if (ждём === null) continue;
  const н = найти(образец, зачем);
  if (н.нет) { проверки.push({ имя: зачем, годно: false, ждали: ждём, вышло: 'НЕ НАЙДЕНО В ТЕКСТЕ' }); continue; }
  п(зачем, н.число, ждём);
}

// Главы стилей названы словом («в одиннадцати главах») — сверяем по счёту.
const словом = ['нуля','одной','двух','трёх','четырёх','пяти','шести','семи',
                'восьми','девяти','десяти','одиннадцати','двенадцати'];
const мГлав = readme.match(/стили в (\S+) глав/);
п('глав стилей (словом)', мГлав ? мГлав[1] : 'нет', словом[главСтилей]);

for (const з of проверки) {
  console.log((з.годно ? '  ' : '✗ ') + з.имя.padEnd(34, '.') +
    (з.годно ? '' : ` в тексте ${з.вышло}, на деле ${з.ждали}`));
}
const плохо = проверки.filter(з => !з.годно).length;
console.log(`\nсверок ${проверки.length}, разошлось ${плохо}`);
process.exit(плохо ? 1 : 0);
