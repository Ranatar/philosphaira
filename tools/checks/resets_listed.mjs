#!/usr/bin/env node
// НИ ОДИН СБРАСЫВАТЕЛЬ КЕШЕЙ НЕ ЗАБЫТ.
//
// В `metrics/scope-reset.js` два перечня, вместе сорок имён, набранных рукой.
// Опасность рукописного перечня не в том, что он длинный, а в том, что
// заводящий сорок первую метрику обязан вспомнить о нём сам. Забудет —
// кеш переживёт смену области, и метрика покажет число, посчитанное для
// другого множества узлов. Молча: ошибки не будет, будет НЕВЕРНОЕ ЧИСЛО.
//
// В readme §10 это стоит долгом с готовым решением — `metrics/registry.js`
// вместо перечня. Реестр честнее, но это правка тридцати модулей и отдельный
// заход; а опасность закрывается уже сейчас — проверкой, что перечень полон.
//
// ЧТО ИМЕННО ПРОВЕРЯЕТСЯ: каждый `invalidate*Cache`, объявленный в metrics/,
// либо зовётся из общего сброса, либо зовётся ИЗ ДРУГОГО сбрасывателя,
// который в общий сброс входит. Второе — законный случай: так устроен
// `invalidatePhilosopherSimilarityCache`, его зовёт `invalidateSimilarityCache`.
import fs from 'node:fs';
import path from 'node:path';
import { КОРЕНЬ } from '../paths.mjs';

const ПАПКА = path.join(КОРЕНЬ, 'app', 'modules', 'metrics');
const СБРОС = path.join(ПАПКА, 'scope-reset.js');

const файлы = fs.readdirSync(ПАПКА).filter(f => f.endsWith('.js'));

const объявлены = new Map();   // имя → файл
for (const f of файлы) {
  const т = fs.readFileSync(path.join(ПАПКА, f), 'utf8');
  for (const m of т.matchAll(/^function (invalidate\w+)\(/gm)) объявлены.set(m[1], f);
}

const сброс = fs.readFileSync(СБРОС, 'utf8');
const прямо = new Set([...сброс.matchAll(/(invalidate\w+)\(\)/g)].map(m => m[1]));

// Через посредника: имя зовётся из тела другого сбрасывателя, который сам
// в общем сбросе есть. Считаем в два круга — глубже вложенности не бывает,
// а если появится, третий круг ничего не изменит и это станет видно.
const покрыты = new Set(прямо);
for (let круг = 0; круг < 2; круг++) {
  for (const [имя, файл] of объявлены) {
    if (!покрыты.has(имя)) continue;
    const т = fs.readFileSync(path.join(ПАПКА, файл), 'utf8');
    const тело = т.slice(т.indexOf(`function ${имя}(`));
    const конец = тело.indexOf('\n    }');
    for (const m of тело.slice(0, конец > 0 ? конец : 2000).matchAll(/(invalidate\w+)\(\)/g))
      if (объявлены.has(m[1])) покрыты.add(m[1]);
  }
}

const забытые = [...объявлены.keys()].filter(и => !покрыты.has(и)).sort();

const проверки = [];
const проверить = (имя, годно, ждали, вышло) =>
  проверки.push({ имя, годно: !!годно, ждали, вышло });

проверить('сбрасыватели найдены', объявлены.size > 30, '>30', объявлены.size);
проверить('ни один сбрасыватель не забыт в общем сбросе',
  забытые.length === 0, 0, забытые.length ? забытые.join(', ') : 0);
// Обратное направление: перечень не должен звать того, чего нет, — так в
// проекте однажды жили призраки в документации.
const призраки = [...прямо].filter(и => !объявлены.has(и) && и !== 'invalidateEverythingForScope');
проверить('в общем сбросе нет призраков', призраки.length === 0, 0,
  призраки.length ? призраки.join(', ') : 0);

for (const п of проверки)
  console.log(`${п.годно ? '✓' : '✗'} ${п.имя}: ждали ${п.ждали}, вышло ${п.вышло}`);
const плохо = проверки.filter(п => !п.годно);
console.log(`\nсбрасывателей ${объявлены.size}, утверждений ${проверки.length}, не сошлось ${плохо.length}`);
process.exit(плохо.length ? 1 : 0);
