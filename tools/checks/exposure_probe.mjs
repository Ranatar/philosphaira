#!/usr/bin/env node
// СЛУЖБА БЕЗ ХОДА, ПРАВО БЕЗ ПРИМЕНЕНИЯ (`exposure_probe`).
//
// ПОВОД. Автор спросил: «может ли быть, что отсутствуют маршруты, которые
// должны быть?» — и оказалось, что может. Три службы работали и не были
// выведены наружу: снятие второго шага (человек мог завести MFA и не мог
// его снять), история правок сущности, удаление пользователя. Плюс право
// `VIEW_LOGS`, объявленное и нигде не проверяемое.
//
// Ни один прибор этого не видел. `product_flow_probe` ходит по HTTP и
// потому замечает лишь то, о чём знает, что надо спросить; отсутствие того,
// чего никто не спрашивал, ему невидимо. Здесь наоборот: спрашивается не
// продукт, а СОГЛАСИЕ СЛОЁВ МЕЖДУ СОБОЙ.
//
//   node tools/checks/exposure_probe.mjs
//
// ЧТО СЧИТАЕТСЯ ЗАКОННЫМ. Не всякая служба обязана иметь ход: шифрование,
// слияние, разбор прав — внутренняя работа. Потому список исключений ведётся
// РУКАМИ, в `decisions/exposure.json`, и каждое исключение снабжено доводом.
// Прибор не решает, что должно быть наружу, — он не даёт ЗАБЫТЬ решить.

import fs from 'node:fs';
import path from 'node:path';
import { КОРЕНЬ } from '../paths.mjs';

const СЕРВЕР = path.join(КОРЕНЬ, 'server', 'src');
const РЕШЕНИЯ = path.join(КОРЕНЬ, 'decisions', 'exposure.json');

if (!fs.existsSync(РЕШЕНИЯ)) {
  console.error('Нет decisions/exposure.json — решения о том, что не выводится наружу');
  process.exit(1);
}
const { внутренние = {}, права_без_хода = {} } = JSON.parse(
  fs.readFileSync(РЕШЕНИЯ, 'utf8'));

const файлы = [];
(function обойти(п) {
  for (const имя of fs.readdirSync(п)) {
    const полный = path.join(п, имя);
    if (fs.statSync(полный).isDirectory()) обойти(полный);
    else if (имя.endsWith('.js')) файлы.push(полный);
  }
})(СЕРВЕР);

const слой = ф => path.relative(СЕРВЕР, ф);
const http = fs.readFileSync(path.join(СЕРВЕР, 'http', 'app.js'), 'utf8');
const всёПодряд = файлы.map(ф => fs.readFileSync(ф, 'utf8')).join('\n');

let плохо = 0;

// ── 1. службы без хода ───────────────────────────────────────────────────
// Слои db/ и http/ не в счёт: первый — хранилище, второй сам и есть ход.
const службы = [];
for (const ф of файлы) {
  const г = слой(ф);
  if (г.startsWith('db/') || г.startsWith('http/')) continue;
  for (const м of fs.readFileSync(ф, 'utf8')
      // \w НЕ ЛОВИТ КИРИЛЛИЦУ, а половина служб здесь названа по-русски.
      // Первая редакция объявила двенадцать существующих служб
      // несуществующими — и предложила убрать про них решения.
      .matchAll(/export (?:async )?function ([\wА-Яа-яЁё$]+)/g)) {
    службы.push({ имя: м[1], где: г });
  }
}
const сироты = службы.filter(с => !http.includes(с.имя) && !(с.имя in внутренние));
if (сироты.length) {
  плохо += сироты.length;
  console.log(`✗ СЛУЖБ БЕЗ ХОДА НАРУЖУ И БЕЗ РЕШЕНИЯ: ${сироты.length}`);
  for (const с of сироты) console.log(`    ${с.имя.padEnd(28)} ${с.где}`);
  console.log('  Либо выведите ход, либо запишите довод в decisions/exposure.json —');
  console.log('  «внутренние»: имя → почему наружу не надо.');
} else {
  console.log(`  служб вне db/ и http/: ${службы.length}, все либо выведены,`
    + ` либо объявлены внутренними (${Object.keys(внутренние).length})`);
}

// ── 2. решения, потерявшие предмет ───────────────────────────────────────
// Список исключений — тоже реестр, и он устаревает молча: служба
// переименована или снята, а довод остался и покрывает пустоту.
const имена = new Set(службы.map(с => с.имя));
const лишние = Object.keys(внутренние).filter(и => !имена.has(и));
if (лишние.length) {
  плохо += лишние.length;
  console.log(`✗ РЕШЕНИЯ О НЕСУЩЕСТВУЮЩИХ СЛУЖБАХ: ${лишние.join(', ')}`);
  console.log('  таких служб больше нет — уберите записи, иначе реестр лжёт');
}

// ── 3. права без применения ──────────────────────────────────────────────
// Объявленное право, которое нигде не спрашивают, — обещание, которое некому
// исполнить: матрица прав показывает его человеку, а действия за ним нет.
const roles = fs.readFileSync(path.join(СЕРВЕР, 'access', 'roles.js'), 'utf8');
const объявлены = [...roles.matchAll(/^ {2}([A-Z_]+):\s+'[\w_]+'/gm)].map(м => м[1]);
const мёртвые = объявлены.filter(и =>
  всёПодряд.split('P.' + и).length - 1 <= 1 && !(и in права_без_хода));
if (мёртвые.length) {
  плохо += мёртвые.length;
  console.log(`✗ ПРАВА, КОТОРЫЕ НИГДЕ НЕ ПРОВЕРЯЮТСЯ: ${мёртвые.join(', ')}`);
  console.log('  право без применения — обещание, которое некому исполнить');
} else {
  console.log(`  прав объявлено ${объявлены.length}, все проверяются`
    + ` или объявлены задельными (${Object.keys(права_без_хода).length})`);
}

if (плохо) {
  console.log('\n✗ СЛОИ РАСХОДЯТСЯ: не согласовано ' + плохо);
} else {
  console.log('\nслужбы и права согласны с ходами наружу');
}
process.exit(плохо ? 1 : 0);
