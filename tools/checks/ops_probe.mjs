#!/usr/bin/env node
// ОПЕРАЦИОННЫЕ ФАКТЫ ДОКУМЕНТАЦИИ (`ops_probe`).
//
// ПОВОД — п. 16 ревизии 27.08 (`doc/gaps-2026-08-27.md`). `plan_probe`
// проверяет, что заявленное СДЕЛАНО, и не видит, что инструкция обещает уже
// сделанное или зовёт несуществующую команду. Дважды за один заход это
// подвело: абзац «Починка на будущее» пережил ту починку на два дня, а
// `rules_probe` читал матрицу прав из файла, откуда её унесли.
//
//   node tools/checks/ops_probe.mjs
//
// ЧТО ПРОВЕРЯЕТСЯ. Только ОПЕРАЦИОННО ЗНАЧИМОЕ: команда, названная в
// инструкции, должна существовать; переменная окружения — читаться кодом;
// путь — быть в дереве; порт по умолчанию — совпадать с кодом. Всю
// документацию разбирать не надо и вредно: разбор прозы даёт ложные тревоги,
// а от них перестают читать прибор.
//
// ГРАНИЦА. Он не судит, ВЕРНА ли инструкция по существу, — только что
// названное в ней существует. «Запустите `npm start`» проверяется; «сперва
// поднимите базу» — нет.

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const acorn = require('acorn');
const eslintScope = require('eslint-scope');
import { КОРЕНЬ } from '../paths.mjs';

const прочесть = отн => {
  const п = path.join(КОРЕНЬ, отн);
  return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
};

const проверки = [];
const п = (имя, годно, ждали, вышло) =>
  проверки.push({ имя, годно: !!годно, ждали, вышло });

// ── 1. команды npm, названные в инструкции, существуют ───────────────────
for (const [файл, пакет] of [
  ['server/README.md', 'server/package.json'],
  ['readme.md', 'package.json'],
]) {
  const текст = прочесть(файл);
  const описание = прочесть(пакет);
  if (!текст || !описание) continue;
  const есть = Object.keys(JSON.parse(описание).scripts ?? {});
  // `\w` НЕ ЛОВИТ КИРИЛЛИЦУ — третий прибор на этих граблях за два дня
  // (были `exposure_probe` и `rename_modules`). Проверено подлогом:
  // «npm run выдуманная-команда» проходило мимо, и прибор был зелен на
  // заведомо ложной инструкции.
  const названы = [...new Set([...текст.matchAll(/`?npm run ([\wА-Яа-яЁё:-]+)`?/g)]
    .map(м => м[1]))];
  const нет = названы.filter(и => !есть.includes(и));
  п(`${файл}: все названные npm-команды существуют`, нет.length === 0,
    'все', нет.join(', ') || 'все на месте');
  // И обратное: команда запуска работника ДОЛЖНА быть названа, иначе
  // человек поднимет один процесс и не узнает, что живое обновление молчит.
  if (файл === 'server/README.md') {
    п('инструкция называет работника уведомлений',
      /notify-worker/.test(текст), 'назван', 'не назван');
  }
}

// ── 2. переменные окружения из инструкции читаются кодом ─────────────────
{
  const текст = прочесть('server/README.md') ?? '';
  const код = [];
  (function обойти(дир) {
    for (const имя of fs.readdirSync(dirПуть(дир))) {
      const полный = path.join(dirПуть(дир), имя);
      if (имя === 'node_modules') continue;
      if (fs.statSync(полный).isDirectory()) обойти(path.join(дир, имя));
      else if (/\.m?js$/.test(имя)) код.push(fs.readFileSync(полный, 'utf8'));
    }
  })('server');
  function dirПуть(д) { return path.join(КОРЕНЬ, д); }
  const всё = код.join('\n');
  // Кириллические прописные тоже ловятся: переменная с русским именем — не
  // то, что стоит заводить, но если она попала в инструкцию, прибор обязан
  // сказать, что кодом она не читается. ЧЕТВЁРТЫЙ РАЗ ЗА ДВА ДНЯ ОБРАЗЕЦ
  // ОКАЗАЛСЯ УЖЕ, ЧЕМ НАДО.
  const названы = [...new Set([...текст.matchAll(/([A-ZА-ЯЁ][A-ZА-ЯЁ0-9_]{3,})=/g)]
    .map(м => м[1]))].filter(и => !['SELECT', 'FROM', 'WHERE'].includes(и));
  // `env[` УБРАНО ИЗ УСЛОВИЯ: одно такое обращение в коде делало
  // проверку бессмысленной — любая выдуманная переменная считалась
  // читаемой. Спрашиваем поимённо.
  const нет = названы.filter(и =>
    !всё.includes(`env.${и}`) && !всё.includes(`env['${и}']`)
    && !всё.includes(`env["${и}"]`));
  п('переменные окружения из инструкции читаются кодом', нет.length === 0,
    'все', нет.join(', ') || 'все читаются');
}

// ── 3. порт по умолчанию в инструкции совпадает с кодом ──────────────────
{
  const текст = прочесть('server/README.md') ?? '';
  const запуск = прочесть('server/scripts/serve.mjs') ?? '';
  const вКоде = (запуск.match(/PORT \|\| (\d+)/) ?? [])[1];
  const вТексте = [...new Set([...текст.matchAll(/127\.0\.0\.1:(\d+)/g)]
    .map(м => м[1]))];
  // ПРОВЕРЯЕТСЯ ОТСУТСТВИЕ ЧУЖИХ, А НЕ НАЛИЧИЕ СВОЕГО. Первая редакция
  // спрашивала «есть ли верный порт среди названных» — и была зелена, когда
  // рядом с верным стоял выдуманный. Утверждение, которое нельзя нарушить
  // добавлением лжи, не стережёт ничего.
  const чужие = вТексте.filter(о => о !== вКоде);
  п('в инструкции нет портов, кроме того, что в коде',
    !вКоде || чужие.length === 0, вКоде ?? '—', чужие.join(', ') || 'нет чужих');
}

// ── 4. пути, названные в инструкции, есть в дереве ───────────────────────
{
  const текст = прочесть('server/README.md') ?? '';
  const пути = [...new Set([...текст.matchAll(
    /`((?:doc|server|app|tools|decisions)\/[\wА-Яа-яЁё./-]+\.(?:md|mjs|js|json|sql))`/g)]
    .map(м => м[1]))];
  const нет = пути.filter(о => !fs.existsSync(path.join(КОРЕНЬ, о))
                            && !fs.existsSync(path.join(КОРЕНЬ, 'server', о)));
  п('пути, названные в инструкции, есть в дереве', нет.length === 0,
    'все', нет.join(', ') || 'все на месте');
}

// ── 5. таблицы, которые сверяют приборы, лежат там, где их ищут ──────────
// `rules_probe` читает напечатанную матрицу прав. После переноса устройства
// в `doc/server-design.md` он получил ноль строк — и был прав. Здесь то же
// проверяется ДЕШЕВО, до полной приёмки.
{
  const где = прочесть('doc/server-design.md') ?? '';
  const строк = [...где.matchAll(/^\|\s*`?\w+`?\s*\|/gm)].length;
  п('матрица прав напечатана там, где её ищет rules_probe', строк >= 10,
    '≥10 строк', строк);
}

// ── 6. кириллических имён в коде продукта нет ────────────────────────────
//
// Правило автора: имена в коде — латиницей. За два дня я нарушил его
// трижды, и каждый раз находилось только ручной проверкой: девять имён
// после фаз шины и заслона согласия, двадцать одно после блока «Основание».
// ЗНАНИЕ ПРАВИЛА ОТ НАРУШЕНИЯ НЕ ЗАЩИЩАЕТ — защищает прибор.
//
// РАЗБОР ОБЛАСТЕЙ ВИДИМОСТИ, А НЕ ПОИСК ПО КЛЮЧЕВЫМ СЛОВАМ.
// Первая редакция искала `const|let|var|function|class` с кириллическим
// именем следом. Она не видела ДОВОДОВ ФУНКЦИЙ — а их в исходнике было 58
// из 60, — не видела разбора (`const { имя } = …`) и переменных `catch`.
// Прибор рапортовал «не сошлось 0» при шести десятках нарушений и тем
// учил доверять себе зря: это хуже отсутствующей проверки, потому что
// отсутствие видно, а ложное подтверждение — нет.
//
// ЧТО СОЗНАТЕЛЬНО НЕ ПРОВЕРЯЕТСЯ:
//  * приборы и оснастка (`server/probes`, `server/scripts`, `tools`) —
//    там кириллица оставлена решением, см. doc/plan-next.md;
//  Решение записано целиком в decisions/cyrillic.json — читайте его прежде,
//  чем отменять исключение.
//  * ИМЕНА ПОЛЕЙ в возвращаемых значениях (`годно`, `вышло`, `версия`,
//    `исход`). Это не имена в коде, а СЛОВАРЬ ПРИЁМКИ: на нём написаны
//    утверждения и отчёты, которые читает человек, разбирая красный
//    прогон. Серверные пробы читают 91 такое поле, `годно` и `вышло` — в
//    восемнадцати пробах каждое. Разбор областей видимости их и не
//    касается: свойство объекта областью видимости не связано.
{
  // СОБСТВЕННЫЙ ОБХОД ДЕРЕВА, А НЕ eslint-scope: тот в здешней сборке не
  // переваривает модули (`import`/`export`) и падает на каждом файле
  // server/src. Нам и не нужны области видимости — нужен перечень МЕСТ
  // СВЯЗЫВАНИЯ, а это разбирается прямым обходом и без чужих ограничений.
  const связывания = (узел, наружу) => {
    if (!узел || typeof узел !== 'object') return;
    const имя = у => {
      if (!у) return;
      if (у.type === 'Identifier') наружу(у.name);
      else if (у.type === 'ObjectPattern') у.properties.forEach(с =>
        имя(с.type === 'RestElement' ? с.argument : с.value));
      else if (у.type === 'ArrayPattern') у.elements.forEach(имя);
      else if (у.type === 'AssignmentPattern') имя(у.left);
      else if (у.type === 'RestElement') имя(у.argument);
    };
    switch (узел.type) {
      case 'VariableDeclarator': имя(узел.id); break;
      case 'FunctionDeclaration':
      case 'FunctionExpression':
      case 'ArrowFunctionExpression':
        имя(узел.id); узел.params.forEach(имя); break;
      case 'ClassDeclaration':
      case 'ClassExpression': имя(узел.id); break;
      case 'CatchClause': имя(узел.param); break;
      default: break;
    }
    for (const ключ of Object.keys(узел)) {
      const в = узел[ключ];
      if (Array.isArray(в)) в.forEach(э => связывания(э, наружу));
      else if (в && typeof в.type === 'string') связывания(в, наружу);
    }
  };

  const собрать = отн => {
    const п = path.join(КОРЕНЬ, отн);
    if (!fs.existsSync(п)) return [];
    const найдено = [];
    const файл = ф => {
      const текст = fs.readFileSync(ф, 'utf8');
      const html = /\.html$/.test(ф);
      const куски = html
        ? [...текст.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(м => м[1])
        : [текст];
      for (const код of куски) {
        if (!код.trim()) continue;
        let ast;
        try {
          ast = acorn.parse(код, { ecmaVersion: 2023,
            sourceType: html ? 'script' : 'module' });
        } catch {
          continue;   // не разобралось — скажет check_modules, не мы
        }
        связывания(ast, и => {
          if (/[А-Яа-яЁё]/.test(и) && и !== 'ЖИВЫЕ') {
            найдено.push(path.basename(ф) + ': ' + и);
          }
        });
      }
    };
    const обойти = д => {
      for (const и of fs.readdirSync(д)) {
        if (и === 'node_modules') continue;
        const полный = path.join(д, и);
        if (fs.statSync(полный).isDirectory()) обойти(полный);
        else if (/\.(m?js|html)$/.test(и)) файл(полный);
      }
    };
    fs.statSync(п).isDirectory() ? обойти(п) : файл(п);
    return найдено;
  };

  // ── СОКРАЩЁННАЯ ЗАПИСЬ, ПОТЕРЯВШАЯ ИМЯ ПОЛЯ ───────────────────────────
  //
  // Переименование разбора `{ метод }` в `{ method }` выглядит как
  // переименование, а меняет ДОГОВОР: разбор начинает читать другое поле.
  // Ровно это и случилось 16 сентября 2026 — семнадцать вызовов слали
  // `{ метод: 'POST' }`, а api разбирал `{ method }`, и все POST и DELETE
  // стали GET. Вход перестал работать.
  //
  // Приборы страницы этого увидеть НЕ МОГЛИ: они гоняются без сервера, а
  // api там выходит первой же строкой (`if (!serverMode) return …`).
  // Нашла page_probe — единственная, что водит страницу ПРИ сервере.
  //
  // Заслон в rename_locals теперь разворачивает такую запись сам, но он
  // стоит в инструменте, а не в приёмке: правку можно внести и руками.
  // Признак прост и не требует знать намерений: вызовы шлют поле
  // кириллицей, а разбор ждёт латиницей — значит имя потерялось.
  {
    const исходник = fs.readFileSync(path.join(КОРЕНЬ, 'source/philosophy_graph_v3.html'), 'utf8');
    const кусок = [...исходник.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)]
      .map(м => м[1]).sort((a, b) => b.length - a.length)[0];
    const ast = acorn.parse(кусок, { ecmaVersion: 2023, sourceType: 'script' });

    // какие кириллические поля где-то ПЕРЕДАЮТСЯ
    const передаются = new Set();
    // какие имена связываются сокращённой записью разбора
    const разбираются = new Set();
    (function обход(узел) {
      if (!узел || typeof узел !== 'object') return;
      if (узел.type === 'ObjectExpression') {
        for (const с of узел.properties) {
          if (с.type === 'Property' && с.key && с.key.type === 'Identifier'
              && /[А-Яа-яЁё]/.test(с.key.name)) передаются.add(с.key.name);
        }
      }
      if (узел.type === 'ObjectPattern') {
        for (const с of узел.properties) {
          if (с.type !== 'Property' || !с.shorthand) continue;
          const им = с.value.type === 'Identifier' ? с.value.name
            : (с.value.type === 'AssignmentPattern' && с.value.left.type === 'Identifier'
               ? с.value.left.name : null);
          if (им) разбираются.add(им);
        }
      }
      for (const ключ of Object.keys(узел)) {
        const в = узел[ключ];
        if (Array.isArray(в)) в.forEach(обход);
        else if (в && typeof в.type === 'string') обход(в);
      }
    })(ast);

    // Сопоставляем по смыслу нельзя, а по факту можно: если поле
    // передаётся кириллицей и НИГДЕ не разбирается — его никто не читает.
    const разбираютсяВсе = new Set();
    (function обход2(узел) {
      if (!узел || typeof узел !== 'object') return;
      if (узел.type === 'ObjectPattern') {
        for (const с of узел.properties) {
          if (с.type === 'Property' && с.key && с.key.type === 'Identifier') {
            разбираютсяВсе.add(с.key.name);
          }
        }
      }
      if (узел.type === 'MemberExpression' && !узел.computed
          && узел.property.type === 'Identifier') разбираютсяВсе.add(узел.property.name);
      for (const ключ of Object.keys(узел)) {
        const в = узел[ключ];
        if (Array.isArray(в)) в.forEach(обход2);
        else if (в && typeof в.type === 'string') обход2(в);
      }
    })(ast);

    // ПОЛЯ ПОЛЕЗНОЙ НАГРУЗКИ — законное исключение. `{ имя, значение }`
    // складываются в сводку замера и уходят на сервер как JSON: их никто
    // не разбирает и разбирать не должен. Отличить их от потерянного имени
    // разбором нельзя — это решение, и оно записано здесь поимённо, а не
    // угадывается. Появится новое такое поле — прибор скажет, и решение
    // будет принято осознанно, а не пропущено.
    const НАГРУЗКА = new Set(['имя', 'значение']);
    const осиротевшие = [...передаются]
      .filter(им => !разбираютсяВсе.has(им) && !НАГРУЗКА.has(им));
    п('переданные кириллические поля кто-то читает', осиротевшие.length === 0, 0,
      осиротевшие.length ? осиротевшие.join(', ') : 0);
  }

  for (const где of ['source/philosophy_graph_v3.html', 'server/src']) {
    const найдено = собрать(где);
    п(`кириллических имён в ${где} нет`, найдено.length === 0, 0,
      найдено.length ? найдено.length + ': ' + найдено.slice(0, 5).join(', ') : 0);
  }
}

// ── ИНСТРУКЦИЯ НЕ ССЫЛАЕТСЯ САМА НА СЕБЯ ─────────────────────────────────
//
// Проверка запуска ПО ИНСТРУКЦИИ, шаг за шагом на чистой базе, нашла
// дефект, которого не видел ни один прибор: абзац ВНУТРИ §5а говорил
// «см. §5а выше». Остаток правки, снявшей устаревшее обещание, — текст
// переписали, ссылку не тронули.
//
// Самоссылка не ломает продукт, но ломает ДОВЕРИЕ к инструкции: читающий
// идёт искать раздел, в котором уже стоит.
{
  const текст = прочесть('server/README.md') ?? '';
  const самоссылки = new Set();
  let нынешний = null;
  for (const строка of текст.split('\n')) {
    const заголовок = строка.match(/^#{2,3}\s+(\d+[а-я]?)\./);
    if (заголовок) { нынешний = заголовок[1]; continue; }
    if (!нынешний) continue;
    for (const с of строка.matchAll(/§\s*(\d+[а-я]?)/g)) {
      if (с[1] === нынешний) самоссылки.add('§' + нынешний);
    }
  }
  п('инструкция не ссылается сама на себя', самоссылки.size === 0, 0,
    [...самоссылки].join(', ') || 0);
}

for (const з of проверки)
  console.log((з.годно ? '  ' : '✗ ') + з.имя.padEnd(56, '.') +
    (з.годно ? '' : ` ждали ${з.ждали}, вышло ${з.вышло}`));
const плохо = проверки.filter(з => !з.годно).length;
console.log(`\nутверждений ${проверки.length}, не сошлось ${плохо}`);
if (плохо) {
  console.log('\n✗ ИНСТРУКЦИЯ РАСХОДИТСЯ С ДЕРЕВОМ. Читающий её сделает то,');
  console.log('  чего сделать нельзя, и решит, что сломан продукт, а не текст.');
}
process.exit(плохо ? 1 : 0);
