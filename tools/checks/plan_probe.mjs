#!/usr/bin/env node
// ОТМЕТКА В ПЛАНЕ ПРОТИВ ДЕРЕВА (`plan_probe`).
//
// ПОВОД. E-1 стоял в плане отмеченным сделанным, а заслон согласованности был
// вплетён ТОЛЬКО в окно концепции: у философа и связи его не было. Нашлось
// это случайно, через месяц по счёту заходов, и только потому, что автор
// попросил продолжить уже сделанное.
//
// ОТМЕТКА — ЭТО НАМЕРЕНИЕ, А НЕ ФАКТ. Пишет её тот же, кто делал работу, и
// пишет по памяти, в конце захода, когда всё кажется сделанным. Признак —
// то, что можно СПРОСИТЬ У ДЕРЕВА: есть ли файл, стоит ли проба в приёмке,
// вплетён ли заслон во все три окна.
//
//   node tools/checks/plan_probe.mjs
//
// ЧЕГО ЭТОТ ПРИБОР НЕ УМЕЕТ И НЕ ДОЛЖЕН. Он не проверяет, что работа сделана
// ХОРОШО, — только что она сделана ВООБЩЕ. Правильность стерегут пробы;
// здесь стережётся честность отметки. Признак, написанный небрежно
// («файл существует»), даст зелёное на пустом файле — потому признаки и
// лежат в `decisions/`, среди решений, а не среди производного.

import fs from 'node:fs';
import path from 'node:path';
import { КОРЕНЬ } from '../paths.mjs';

const СВОД = path.join(КОРЕНЬ, 'decisions', 'plan_signs.json');
if (!fs.existsSync(СВОД)) {
  console.error('Нет decisions/plan_signs.json — признаки не заведены');
  process.exit(1);
}

const { признаки } = JSON.parse(fs.readFileSync(СВОД, 'utf8'));
const кэш = new Map();
const прочесть = отн => {
  if (!кэш.has(отн)) {
    const п = path.join(КОРЕНЬ, отн);
    кэш.set(отн, fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null);
  }
  return кэш.get(отн);
};

const поПунктам = new Map();
let плохо = 0;

for (const [пункт, что, род, где] of признаки) {
  let сошлось = false, пояснение = '';
  if (род === 'есть') {
    сошлось = fs.existsSync(path.join(КОРЕНЬ, где));
    пояснение = 'файла нет';
  } else {
    const [файл, подстрока] = где.split('|');
    const текст = прочесть(файл);
    if (текст === null) { пояснение = `файла ${файл} нет`; }
    else {
      const внутри = текст.includes(подстрока);
      сошлось = род === 'нет-внутри' ? !внутри : внутри;
      пояснение = род === 'нет-внутри'
        ? `в ${файл} есть «${подстрока}», а быть не должно`
        : `в ${файл} нет «${подстрока.slice(0, 50)}»`;
    }
  }
  if (!поПунктам.has(пункт)) поПунктам.set(пункт, []);
  поПунктам.get(пункт).push({ что, сошлось, пояснение });
  if (!сошлось) плохо++;
}

for (const [пункт, список] of поПунктам) {
  const плохих = список.filter(з => !з.сошлось);
  if (!плохих.length) {
    console.log(`  ${пункт}`.padEnd(8) + `признаков ${список.length}, все на месте`);
  } else {
    console.log(`✗ ${пункт}: НЕ ПОДТВЕРЖДЕНО ${плохих.length} из ${список.length}`);
    for (const з of плохих) console.log(`    ${з.что} — ${з.пояснение}`);
  }
}

if (плохо) {
  console.log(`\n✗ ОТМЕТКА В ПЛАНЕ РАСХОДИТСЯ С ДЕРЕВОМ: не подтвердилось ${плохо}.`);
  console.log('  Либо доделайте, либо снимите отметку — но не оставляйте как есть:');
  console.log('  план, которому нельзя верить, хуже отсутствующего плана.');
} else {
  console.log(`\nпризнаков ${признаки.length}, отметки в плане подтверждены деревом`);
}
process.exit(плохо ? 1 : 0);
