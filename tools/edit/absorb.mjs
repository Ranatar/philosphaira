#!/usr/bin/env node
// ОБРАТНЫЙ ПЕРЕНОС: app/data/*.json → литералы исходника.
//
// ЗАЧЕМ. У базы уже два писателя — сохранение из приложения и рука; с
// сервером станет три. Рукотворная правда живёт в литералах исходника, а
// правки приходят в app/data/*.json. Переносить их обратно вручную нельзя:
// наборов семь, и однажды скопируют не все. Особенно легко забыть позиции —
// они связаны с базой отпечатком, и перенос одной базы без них означает
// протухший набор и откат на живую симуляцию.
//
// ПОЧЕМУ ЭТО БЕЗОПАСНО (замерено, а не предположено). split НЕ переносит
// текст литерала: он вычисляет его и заново сериализует
// JSON.stringify(значение, null, 1). Все семь наборов оказались НЕПОДВИЖНОЙ
// ТОЧКОЙ этого преобразования, и круг «JSON → литерал JS → JSON» даёт байт в
// байт то же самое. Значит вставка содержимого .json на место литерала
// безопасна, а форматирование роли не играет — оно всё равно нормализуется.
//
// ЧЕМ ПРОВЕРЯЕТСЯ. Заслон уже есть и другого не нужно: после переноса
// пересборка в чистое место обязана совпасть с app/ побайтово.
//
//   node tools/edit/absorb.mjs              перенести все наборы
//   node tools/edit/absorb.mjs --показать   только сказать, что изменилось бы
import fs from 'node:fs';
import path from 'node:path';
import { ИСХОДНИК, ДЕРЕВО } from '../paths.mjs';

const ТОЛЬКО_ПОКАЗАТЬ = process.argv.includes('--показать');

// Список наборов НЕ переписывается здесь: он читается из split.mjs, где
// объявлен единожды. Правило, записанное дважды, однажды разъедется.
const splitТекст = fs.readFileSync(path.join(path.dirname(new URL(import.meta.url).pathname), 'split.mjs'), 'utf8');
const m = splitТекст.match(/const RAW_DATA = (\[[^\]]*\]);/);
if (!m) { console.error('не нашёл RAW_DATA в split.mjs'); process.exit(2); }
const НАБОРЫ = JSON.parse(m[1].replace(/'/g, '"'));

let исходник = fs.readFileSync(ИСХОДНИК, 'utf8');
const отчёт = [];
let изменено = 0;

for (const имя of НАБОРЫ) {
  const файл = path.join(ДЕРЕВО, 'data', имя + '.json');
  if (!fs.existsSync(файл)) {
    console.error(`нет ${файл} — сперва соберите дерево`);
    process.exit(2);
  }
  const текст = fs.readFileSync(файл, 'utf8');
  let значение;
  try { значение = JSON.parse(текст); }
  catch (e) { console.error(`${имя}.json не разбирается: ${e.message}`); process.exit(2); }

  // Границы литерала: от `const <имя> = ` до строки, где на нужном отступе
  // стоит закрывающая скобка с точкой с запятой. Разбор здесь избыточен —
  // объявления наборов однотипны и стоят в корне области видимости.
  const начало = new RegExp('^([ \\t]*)const ' + имя + ' = ', 'm');
  const с = исходник.match(начало);
  if (!с) { console.error(`в исходнике нет объявления ${имя}`); process.exit(2); }
  const отступ = с[1];
  const от = с.index;
  const открывающая = исходник[от + с[0].length];
  const закрывающая = открывающая === '[' ? ']' : '}';
  // конец: либо однострочный литерал, либо строка «<отступ><закрывающая>;»
  let до;
  const однострочный = исходник.indexOf('\n', от);
  const перваяСтрока = исходник.slice(от, однострочный);
  if (перваяСтрока.trimEnd().endsWith(';')) {
    до = однострочный;
  } else {
    const маяк = '\n' + отступ + закрывающая + ';';
    const k = исходник.indexOf(маяк, от);
    if (k < 0) { console.error(`не нашёл конец литерала ${имя}`); process.exit(2); }
    до = k + маяк.length;
  }

  const было = исходник.slice(от, до);

  // СРАВНИВАЮТСЯ ЗНАЧЕНИЯ, А НЕ ТЕКСТ. Шесть первых наборов человек правит
  // руками: там ключи без кавычек, отступ в два пробела и перенос строки на
  // каждое поле. Сверка по тексту объявила бы их изменившимися ВСЕГДА и
  // переписала бы читаемый литерал в одну строку — правка ради формата, от
  // которой diff распухает, а смысла нет.
  const телоБыло = было.slice(было.indexOf('=') + 1).trim().replace(/;$/, '');
  let прежнее;
  try { прежнее = new Function('return (' + телоБыло + ')')(); }
  catch (e) { console.error(`литерал ${имя} в исходнике не разбирается: ${e.message}`); process.exit(2); }
  if (JSON.stringify(прежнее) === JSON.stringify(значение)) {
    отчёт.push(`${имя}: значение совпадает`);
    continue;
  }
  // ОТСТУП ОБЯЗАТЕЛЕН, И ВОТ ПОЧЕМУ. Конец литерала эта же программа ищет по
  // строке «<отступ><закрывающая>;». Записав JSON без отступа, она перестаёт
  // находить собственную запись при следующем прогоне — проверено: подлог,
  // перенесённый в исходник, потом не вычищался обратно и утекал в дерево.
  const тело = JSON.stringify(значение, null, 1)
    .split('\n').map((л, i) => (i ? отступ + л : л)).join('\n');
  const стало = отступ + 'const ' + имя + ' = ' + тело + ';';
  отчёт.push(`${имя}: ${было.length} → ${стало.length} знаков`);
  изменено++;
  if (!ТОЛЬКО_ПОКАЗАТЬ) исходник = исходник.slice(0, от) + стало + исходник.slice(до);
}

for (const с of отчёт) console.log('  ' + с);
if (ТОЛЬКО_ПОКАЗАТЬ) {
  console.log(`\nизменилось бы наборов: ${изменено} (ничего не записано)`);
  process.exit(0);
}
if (!изменено) { console.log('\nисходник уже согласен с деревом'); process.exit(0); }
fs.writeFileSync(ИСХОДНИК, исходник);
console.log(`\nперенесено наборов: ${изменено}`);
console.log('ОБЯЗАТЕЛЬНО ДАЛЬШЕ: node tools/remap.mjs собрать, затем сверить,');
console.log('что пересборка в чистое место совпадает с app/ побайтово.');
