#!/usr/bin/env node
// ПЕРЕИМЕНОВАНИЕ ИМЁН В СВЯЗНОМ НАБОРЕ МОДУЛЕЙ (`rename_modules.mjs`).
//
// ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ `rename.mjs`. Тот правит ОДИН файл — одностраничный
// исходник, где всё живёт в одной области видимости. Здесь набор модулей, и
// имя может УЕЗЖАТЬ В СОСЕДНИЕ ФАЙЛЫ: `export const НАБОРЫ` из
// `graph/schema.js` ввозится в четырёх местах. Переименовать его в одном
// файле значит сломать остальные — молча, потому что `import { НАБОРЫ }`
// просто даст undefined.
//
//   node tools/edit/rename_modules.mjs проверить server/src старое=новое […]
//   node tools/edit/rename_modules.mjs применить server/src старое=новое […]
//
// ЧТО ПРАВИТСЯ. Объявление, все ссылки внутри своего модуля, строка вывоза
// и КАЖДЫЙ ввоз в других файлах. Ввоз с переименованием (`import { А as Б }`)
// оставляется как есть, только левая часть меняется: местное имя — дело
// того файла.
//
// ЧЕГО ПРОГРАММА НЕ ДЕЛАЕТ. Не трогает строковые литералы (имя в строке —
// не имя), не трогает свойства объектов (`о.НАБОРЫ` — это ключ), и
// ОТКАЗЫВАЕТСЯ, если новое имя уже занято хоть в одном из затронутых
// файлов: молча вышло бы затенение.

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { КОРЕНЬ } from '../paths.mjs';

const require = createRequire(import.meta.url);

// ГРАНИЦА СЛОВА `\b` НЕ ГОДИТСЯ ДЛЯ КИРИЛЛИЦЫ. Она определяется по `\w`,
// то есть по латинице с цифрами; между пробелом и буквой «Н» границы для
// неё НЕТ, и `\bНАБОРЫ\b` не находит ничего. На этом уже спотыкался
// exposure_probe, и здесь то же самое: ввозы вывозимого имени не находились,
// а программа бодро сообщала, что переименование безопасно.
const целиком = имя => new RegExp(
  `(?<![\\wА-Яа-яЁё$])${имя}(?![\\wА-Яа-яЁё$])`, 'g');
const acorn = require('acorn');
const eslintScope = require('eslint-scope');

const режим = process.argv[2];
const папка = process.argv[3];
const пары = process.argv.slice(4).map(п => {
  const [слева, новое] = п.split('=');
  if (!слева || !новое) { console.error(`Негодная пара: ${п}`); process.exit(1); }
  // ФАЙЛ УКАЗЫВАЕТСЯ ЧЕРЕЗ СОБАКУ: `изм@commits/apply.js=change`. Без этого
  // недоступны ходовые имена: `к`, `и`, `с` объявлены в разных модулях, и
  // это РАЗНЫЕ переменные, а не одна.
  // Если в одном файле таких имён несколько — различаются номером по
  // порядку объявления: `биты@src/auth/totp.js:2=bits`.
  const [старое, место] = слева.split('@');
  const [файл, номер] = (место || '').split(':');
  return { старое, новое, файл: файл || null, номер: номер ? Number(номер) : null };
});
if (!['проверить', 'применить'].includes(режим) || !папка || !пары.length) {
  console.error('node tools/edit/rename_modules.mjs проверить|применить <папка> старое=новое […]');
  process.exit(1);
}

const корень = path.join(КОРЕНЬ, папка);
const файлы = [];
(function обойти(п) {
  for (const имя of fs.readdirSync(п)) {
    const полный = path.join(п, имя);
    // node_modules — чужой код, его переименовывать нельзя ни при каких
    // обстоятельствах: он не наш и восстановится при следующей установке.
    if (имя === 'node_modules') continue;
    if (fs.statSync(полный).isDirectory()) обойти(полный);
    else if (/\.m?js$/.test(имя)) файлы.push(полный);
  }
})(корень);

/**
 * Сокращённые записи свойств: `{ имя }` вместо `{ имя: имя }`.
 *
 * ЗДЕСЬ ИДЕНТИФИКАТОР ОДНОВРЕМЕННО И КЛЮЧ, и переименовать его нельзя —
 * получится `{ setName }`, то есть ПОЛЕ С ДРУГИМ ИМЕНЕМ, а читающий код
 * ищет прежнее. Поймано на `auth_probe`: правка довода `имя` переименовала
 * поле записи, и `п.имя.padEnd` упало на undefined.
 *
 * Правильно — развернуть запись: `{ имя: setName }`. Поле остаётся, имя
 * переменной меняется.
 */
function сокращённые(ast) {
  const итог = new Map();   // начало диапазона идентификатора → true
  (function обойти(у) {
    if (!у || typeof у !== 'object') return;
    if (Array.isArray(у)) { у.forEach(обойти); return; }
    if (у.type === 'Property' && у.shorthand && у.key?.range) {
      итог.set(у.key.range[0], у.key.name);
    }
    for (const к of Object.keys(у)) if (к !== 'range') обойти(у[к]);
  })(ast);
  return итог;
}

/** Разбор одного модуля: дерево, области, содержимое. */
function разобрать(ф) {
  const код = fs.readFileSync(ф, 'utf8');
  const ast = acorn.parse(код, { ecmaVersion: 2023, sourceType: 'module', ranges: true });
  const карта = eslintScope.analyze(ast, {
    ecmaVersion: 2023, sourceType: 'module', ecmaFeatures: { globalReturn: false } });
  return { ф, код, ast, карта, кратко: сокращённые(ast) };
}

const разбор = new Map(файлы.map(ф => [ф, разобрать(ф)]));

/** Все области модуля, где имя объявлено. */
function объявления(м, имя) {
  const итог = [];
  (function обойти(о) {
    for (const пер of о.variables) if (пер.name === имя) итог.push({ область: о, пер });
    о.childScopes.forEach(обойти);
  })(м.карта.globalScope);
  return итог;
}

const видноВ = (область, имя) => {
  for (let о = область; о; о = о.upper) if (о.variables.some(п => п.name === имя)) return о;
  return null;
};

let отказов = 0;
const правки = new Map();   // файл → [{range, новое}]
const добавить = (ф, range, новое, м) => {
  if (!правки.has(ф)) правки.set(ф, []);
  // Сокращённая запись разворачивается, чтобы поле сохранило прежнее имя.
  const ключ = м?.кратко?.get(range[0]);
  правки.get(ф).push({ range, новое: ключ ? `${ключ}: ${новое}` : новое });
};

for (const { старое, новое, файл, номер } of пары) {
  // ── где объявлено ──────────────────────────────────────────────────────
  // ОДНО ОБЪЯВЛЕНИЕ — ОДНА ЗАПИСЬ. Для модуля eslint-scope заводит и
  // глобальную область, и область модуля, и переменная верхнего уровня
  // видна в обеих: без отсева по месту определения всякое имя выглядело бы
  // объявленным дважды, и программа отказывала бы всегда.
  let где = [];
  const виденные = new Set();
  for (const м of разбор.values()) {
    for (const о of объявления(м, старое)) {
      // ВВОЗ — НЕ ОБЪЯВЛЕНИЕ. `import { НАБОРЫ }` заводит переменную в том
      // модуле, и без этого отсева всякое вывозимое имя выглядело бы
      // объявленным столько раз, сколько модулей его ввозят.
      const род = о.пер.defs[0]?.type;
      if (род === 'ImportBinding') continue;
      const метка = м.ф + ':' + (о.пер.defs[0]?.name?.range?.[0] ?? -1);
      if (виденные.has(метка)) continue;
      виденные.add(метка);
      где.push({ м, ...о });
    }
  }
  if (файл) {
    где = где.filter(з => path.relative(корень, з.м.ф).replace(/\\/g, '/') === файл);
    if (!где.length) {
      console.log(`✗ ${старое}@${файл}: в этом файле такого имени нет`);
      отказов++;
      continue;
    }
  }
  if (!где.length) { console.log(`✗ ${старое}: такого имени в наборе нет`); отказов++; continue; }
  if (номер) {
    if (номер < 1 || номер > где.length) {
      console.log(`✗ ${старое}@${файл}:${номер} — таких там ${где.length}`);
      отказов++;
      continue;
    }
    где = [где[номер - 1]];
  }
  if (где.length > 1) {
    console.log(`✗ ${старое}: объявлено в ${где.length} местах — это разные имена:`);
    const имена = где.map(з => path.relative(корень, з.м.ф).replace(/\\/g, '/'));
    if (new Set(имена).size === 1) {
      // ОДИН ФАЙЛ, НЕСКОЛЬКО ОБЪЯВЛЕНИЙ. Подсказывать файл бессмысленно —
      // он и так один; различаем номером по порядку объявления.
      console.log(`   в ${имена[0]} их ${где.length}; различите номером:`);
      где.forEach((з, i) => console.log(
        `     ${старое}@${имена[0]}:${i + 1}=${новое}`));
    } else {
      console.log('   укажите файл: ' + имена.slice(0, 6).map(ф =>
        `${старое}@${ф}=${новое}`).join(' '));
    }
    отказов++;
    continue;
  }
  const { м, область, пер } = где[0];
  const свой = path.relative(корень, м.ф);

  // ── занято ли новое имя ────────────────────────────────────────────────
  if (видноВ(область, новое)) {
    console.log(`✗ ${старое} → ${новое}: имя ${новое} уже видно в ${свой}`);
    отказов++;
    continue;
  }

  // Вывозится ли имя наружу — тогда затронуты и ввозящие модули.
  // ВЫВОЗ ОПРЕДЕЛЯЕТСЯ ПО ДЕРЕВУ, А НЕ ПО ТЕКСТУ ВОКРУГ. Первая редакция
  // смотрела сорок знаков перед объявлением и не нашла ни одного вывоза:
  // `export const НАБОРЫ` разбирается в узел ExportNamedDeclaration, чьё
  // начало лежит РАНЬШЕ имени, а не за сорок знаков до него.
  const вывозится = м.ast.body.some(у => {
    if (у.type === 'ExportNamedDeclaration') {
      if (у.declaration?.declarations?.some(д => д.id?.name === старое)) return true;
      if (у.declaration?.id?.name === старое) return true;
      if (у.specifiers?.some(с => с.local?.name === старое)) return true;
    }
    return false;
  });

  let ввозящих = 0;
  if (вывозится) {
    for (const другой of разбор.values()) {
      if (другой.ф === м.ф) continue;
      const ввоз = new RegExp(
        `import\\s*\\{([^}]*)\\}\\s*from\\s*['"][^'"]+['"]`, 'g');
      for (const сов of другой.код.matchAll(ввоз)) {
        if (!целиком(старое).test(сов[1])) continue;
        // Занято ли новое имя в ТОМ файле — иначе ввоз затенил бы своё.
        if (объявления(другой, новое).length) {
          console.log(`✗ ${старое} → ${новое}: в ${path.relative(корень, другой.ф)}`
            + ` имя ${новое} уже своё — ввоз затенил бы его`);
          отказов++;
          continue;
        }
        ввозящих++;
        // ССЫЛКИ БЕРУТСЯ У ПЕРЕМЕННОЙ ВВОЗА, А НЕ ИЗ `through`.
        // `import { X }` заводит в модуле обычную переменную, и обращения к
        // ней — её собственные references. Первая редакция искала сквозные
        // ссылки (through), не нашла ни одной и правила ТОЛЬКО СТРОКУ
        // ВВОЗА: `import { SET_BY_KIND }` при `НАБОР_ПО_РОДУ` в теле.
        // Отказ был бы лучше: код падал на первом же обращении.
        const мест = [];
        for (const о of объявления(другой, старое)) {
          for (const опр of о.пер.defs) if (опр.name) мест.push(опр.name.range);
          for (const ссылка of о.пер.references) мест.push(ссылка.identifier.range);
        }
        const внутриВвоза = сов.index + сов[0].indexOf(сов[1]);
        for (const сов2 of сов[1].matchAll(целиком(старое))) {
          мест.push([внутриВвоза + сов2.index, внутриВвоза + сов2.index + старое.length]);
        }
        for (const [a, b] of [...new Map(мест.map(р => [р[0], р])).values()]) {
          добавить(другой.ф, [a, b], новое, другой);
        }
      }
    }
  }

  const мест = [];
  for (const о of пер.defs) if (о.name) мест.push(о.name.range);
  for (const ссылка of пер.references) мест.push(ссылка.identifier.range);
  // Строка вывоза `export { … }` — не ссылка для разбора, ищем отдельно.
  for (const сов of м.код.matchAll(new RegExp(`export\\s*\\{[^}]*\\}`, 'g'))) {
    for (const сов2 of сов[0].matchAll(целиком(старое))) {
      мест.push([сов.index + сов2.index, сов.index + сов2.index + старое.length]);
    }
  }
  const единственные = [...new Map(мест.map(р => [р[0], р])).values()];
  for (const р of единственные) добавить(м.ф, р, новое, м);

  console.log(`  ${старое} → ${новое}: ${свой}, мест ${единственные.length}`
    + (ввозящих ? `; ввозят ещё ${ввозящих} модулей` : ''));
}

if (отказов) { console.log(`\n✗ ОТКАЗОВ ${отказов} — ничего не изменено`); process.exit(1); }
if (режим === 'проверить') {
  console.log('\nвсе переименования безопасны');
  process.exit(0);
}

for (const [ф, список] of правки) {
  let текст = fs.readFileSync(ф, 'utf8');
  for (const { range, новое } of [...список].sort((а, б) => б.range[0] - а.range[0])) {
    текст = текст.slice(0, range[0]) + новое + текст.slice(range[1]);
  }
  fs.writeFileSync(ф, текст);
}
console.log(`\n✓ правлено файлов: ${правки.size}`);
