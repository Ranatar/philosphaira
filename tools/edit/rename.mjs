#!/usr/bin/env node
// БЕЗОПАСНОЕ ПЕРЕИМЕНОВАНИЕ ИМЁН В ИСХОДНИКЕ (`rename.mjs`).
//
// ПОВОД. 25 августа я переименовывал свои идентификаторы автозаменой по
// образцу и получил две беды разом:
//   1) `\bсередина\b` задело ОТОБРАЖАЕМЫЙ ТЕКСТ — описания философов и
//      название концепции «Золотая середина»;
//   2) в `impact.js` замена `с` → `rel` дала КОЛЛИЗИЮ: `rel` уже был доводом
//      цикла, и служба падала на пустом месте.
// Первую беду стережёт `content_probe.mjs`. Вторую — эта программа: она не
// проверяет постфактум, а ПЕРЕИМЕНОВЫВАЕТ ПРАВИЛЬНО.
//
//   node tools/edit/rename.mjs проверить старое=новое [ещё=пары…]
//   node tools/edit/rename.mjs применить старое=новое [ещё=пары…]
//
// КАК ОНА РАБОТАЕТ. Разбирает исходник теми же acorn и eslint-scope, что и
// разбивка, и правит ТОЛЬКО настоящие вхождения идентификатора: объявление и
// ссылки на него, разрешённые по области видимости. Строка `'Золотая
// середина'` для разбора — литерал, а не имя, и остаётся нетронутой в любом
// случае. Свойство `о.середина` — тоже не имя.
//
// ЧЕГО ОНА НЕ СДЕЛАЕТ. Не переименует, если новое имя УЖЕ ЗАНЯТО в той же
// области или видно в ней снаружи: молча получилось бы затенение, при
// котором код разбирается, а ссылки уходят не туда. Отказ с указанием места
// лучше тихой поломки.

import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { ИСХОДНИК, КОРЕНЬ } from '../paths.mjs';

const require = createRequire(import.meta.url);
const acorn = require('acorn');
const eslintScope = require('eslint-scope');

const режим = process.argv[2];
const пары = process.argv.slice(3).map(п => {
  const [слева, новое] = п.split('=');
  if (!слева || !новое) {
    console.error(`Негодная пара: ${п}. Нужно старое=новое или старое@где=новое`);
    process.exit(1);
  }
  // ОБЛАСТЬ УКАЗЫВАЕТСЯ ЧЕРЕЗ СОБАКУ. Без неё нельзя тронуть ни одно из
  // ходовых имён: `ответ` объявлен в ДЕВЯТНАДЦАТИ разных функциях, и это
  // девятнадцать разных переменных. Отказ трогать их скопом — правильная
  // осторожность, но работать с ней было нельзя.
  // Место записывается как `имя@функция` или, если в одной функции таких
  // переменных несколько, `имя@функция:2` — по порядку объявления.
  const [старое, место] = слева.split('@');
  const [где, номер] = (место || '').split(':');
  return { старое, новое, где: где || null, номер: номер ? Number(номер) : null };
});

if (!['проверить', 'применить'].includes(режим) || !пары.length) {
  console.error('node tools/edit/rename.mjs проверить|применить старое=новое […]');
  process.exit(1);
}

const html = fs.readFileSync(ИСХОДНИК, 'utf8');

// Скрипт страницы — самый длинный блок <script>: так же его берёт разбивка.
const блоки = [...html.matchAll(/<script(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/g)];
const блок = блоки.reduce((а, б) => (б[1].length > а[1].length ? б : а));
const начало = блок.index + блок[0].indexOf(блок[1]);
const код = блок[1];

const ast = acorn.parse(код, { ecmaVersion: 2023, sourceType: 'script', ranges: true });

/**
 * Сокращённые записи свойств: `{ тело }` вместо `{ тело: тело }`. Бывают и в
 * ЛИТЕРАЛАХ, и в РАЗБОРЕ ДОВОДА (`function api(path, { метод, тело })`).
 *
 * Идентификатор здесь одновременно и КЛЮЧ. Переименовать его нельзя —
 * получится поле с другим именем, а зовущие передают прежнее. Поймано
 * дорого: `api(path, { метод, тело })` стало `{ метод, body }`, тринадцать
 * мест продолжали слать `тело:`, и вход молча уходил с пустым телом —
 * сервер отвечал «неверный адрес или пароль» на верный пароль.
 *
 * Правильно — развернуть: `{ тело: body }`.
 */
const сокращённые = (() => {
  const итог = new Map();
  (function обойти(у) {
    if (!у || typeof у !== 'object') return;
    if (Array.isArray(у)) { у.forEach(обойти); return; }
    if (у.type === 'Property' && у.shorthand && у.key?.range) итог.set(у.key.range[0], у.key.name);
    for (const к of Object.keys(у)) if (к !== 'range') обойти(у[к]);
  })(ast);
  return итог;
})();
const карта = eslintScope.analyze(ast, { ecmaVersion: 2023, sourceType: 'script' });

/** Все области, где имя объявлено. */
function объявленияИмени(имя) {
  const найдено = [];
  const обойти = область => {
    for (const пер of область.variables) if (пер.name === имя) найдено.push({ область, пер });
    область.childScopes.forEach(обойти);
  };
  обойти(карта.globalScope);
  return найдено;
}

/**
 * Имя ближайшей объемлющей функции — то, чем человек называет место:
 * `ответ@submitAuth`. Область без имени (блок, стрелка) отдаёт имя своей
 * родительской функции, иначе указывать было бы не на что.
 */
function имяОбласти(область) {
  for (let о = область; о; о = о.upper) {
    const у = о.block;
    if (у && у.id && у.id.name) return у.id.name;
    if (о.type === 'global') return 'глобально';
  }
  return null;
}

/** Видно ли имя в области — своё или доставшееся снаружи. */
function видноВОбласти(область, имя) {
  for (let о = область; о; о = о.upper) {
    if (о.variables.some(п => п.name === имя)) return о;
  }
  return null;
}

let отказов = 0;
const правки = [];

for (const { старое, новое, где, номер } of пары) {
  const объявления = объявленияИмени(старое);
  if (!объявления.length) {
    console.log(`✗ ${старое}: такого имени в исходнике нет`);
    отказов++;
    continue;
  }
  let выбранные = объявления;
  if (где) {
    выбранные = объявления.filter(о => имяОбласти(о.область) === где);
    if (!выбранные.length) {
      console.log(`✗ ${старое}@${где}: в области «${где}» такого имени нет.`);
      console.log('   есть в: ' + [...new Set(объявления.map(о => имяОбласти(о.область)))]
        .join(', ').slice(0, 200));
      отказов++;
      continue;
    }
  }
  if (номер) {
    if (номер < 1 || номер > выбранные.length) {
      console.log(`✗ ${старое}@${где}:${номер} — таких там ${выбранные.length}`);
      отказов++;
      continue;
    }
    выбранные = [выбранные[номер - 1]];
  }
  if (выбранные.length > 1) {
    const имена = выбранные.map(о => имяОбласти(о.область));
    const однимИменем = new Set(имена).size === 1;
    console.log(`✗ ${старое}: объявлено в ${выбранные.length} областях —`
      + ' переименование затронуло бы все сразу, а это разные имена.');
    if (однимИменем) {
      // ОДНО ИМЯ ОБЛАСТИ НА НЕСКОЛЬКО ПЕРЕМЕННЫХ. Так бывает, когда внутри
      // функции есть блок или стрелка со своим таким же именем. Подсказывать
      // ту же команду бессмысленно — различаем номером и показываем строки.
      console.log(`   в «${имена[0]}» их ${выбранные.length}; различите номером:`);
      выбранные.forEach((о, i) => {
        const место = о.пер.defs[0]?.name?.range?.[0] ?? 0;
        const строка = код.slice(0, место).split('\n').length;
        console.log(`     ${старое}@${имена[0]}:${i + 1}=${новое}   (строка ${строка})`);
      });
    } else {
      console.log('   укажите область: ' + [...new Set(имена)]
        .slice(0, 8).map(и => `${старое}@${и}=${новое}`).join(' '));
    }
    отказов++;
    continue;
  }
  const { область, пер } = выбранные[0];

  // ЗАНЯТОСТЬ ЦЕЛЕВОГО ИМЕНИ — то, ради чего программа написана.
  const занято = видноВОбласти(область, новое);
  if (занято) {
    console.log(`✗ ${старое} → ${новое}: имя ${новое} УЖЕ ВИДНО в этой области`
      + ` (${занято === область ? 'объявлено здесь же' : 'досталось снаружи'})`);
    console.log('   переименование дало бы затенение: код разберётся, а ссылки'
      + ' уйдут не туда');
    отказов++;
    continue;
  }

  // Собираем места: объявление и все разрешённые ссылки.
  const места = [];
  for (const о of пер.defs) if (о.name) места.push(о.name.range);
  for (const ссылка of пер.references) места.push(ссылка.identifier.range);
  // Ссылки, разрешённые в эту переменную из вложенных областей, eslint-scope
  // уже собрал в `пер.references` — отдельного обхода не нужно.

  const единственные = [...new Map(места.map(р => [р[0], р])).values()];
  console.log(`  ${старое} → ${новое}: мест ${единственные.length}`);

  // ГРАНИЦА ПРИМЕНИМОСТИ, О КОТОРОЙ НАДО СКАЗАТЬ ВСЛУХ. Вызовы из разметки
  // (`onclick="забанить(…)"`) для разбора — СТРОКА, а не имя, и здесь они не
  // правятся. Для страницы, где половина обработчиков висит в атрибутах, это
  // не мелочь: переименуешь функцию — и кнопка перестанет работать молча.
  const вРазметке = [...html.matchAll(
    new RegExp('on[a-z]+="[^"]*\\b' + старое + '\\b[^"]*"', 'g'))];
  if (вРазметке.length) {
    console.log(`   ⚠ имя встречается в ${вРазметке.length} атрибутах разметки`
      + ' — они НЕ правятся здесь и сломаются:');
    for (const м of вРазметке.slice(0, 3)) console.log('     ' + м[0].slice(0, 80));
    console.log('   правьте их отдельно, вручную, и сверьтесь обходом');
  }
  правки.push(...единственные.map(р => ({ р, новое })));
}

if (отказов) {
  console.log(`\n✗ ОТКАЗОВ ${отказов} — ничего не изменено`);
  process.exit(1);
}

if (режим === 'проверить') {
  console.log('\nвсе переименования безопасны; применить:'
    + '\n  node tools/edit/rename.mjs применить ' + process.argv.slice(3).join(' '));
  process.exit(0);
}

// Правим С КОНЦА, чтобы сдвиги не сбивали оставшиеся места.
правки.sort((а, б) => б.р[0] - а.р[0]);
let итог = html;
for (const { р, новое } of правки) {
  const ключ = сокращённые.get(р[0]);
  итог = итог.slice(0, начало + р[0]) + (ключ ? `${ключ}: ${новое}` : новое)
       + итог.slice(начало + р[1]);
}
fs.writeFileSync(ИСХОДНИК, итог);

// РЕЕСТР ДОМОВ ПРАВИТСЯ ЗАОДНО. Имя живёт в ДВУХ местах: в исходнике и в
// `decisions/assign_names.json`, где записано, в какой модуль оно поедет при
// разбивке. Правя одно и забывая другое, получаешь отказ сборки «нет модуля
// для имени» — не страшно, но каждый раз вручную. Забыть тут проще, чем
// вспомнить: реестр не на виду.
const реестр = path.join(КОРЕНЬ, 'decisions', 'assign_names.json');
if (fs.existsSync(реестр)) {
  const j = JSON.parse(fs.readFileSync(реестр, 'utf8'));
  let тронуто = 0;
  for (const { старое, новое } of пары) {
    if (j.по_имени && старое in j.по_имени) {
      j.по_имени[новое] = j.по_имени[старое];
      delete j.по_имени[старое];
      тронуто++;
    }
    // Раздел `новые` — пометка происхождения, а не дом (doc/build.md), но
    // имя в нём обязано пройти через тот же словарь, иначе перестанет
    // сходиться с исходником. Прежде это делал rename_globals.mjs.
    if (Array.isArray(j.новые) && j.новые.includes(старое)) {
      j.новые = j.новые.map(x => x === старое ? новое : x);
      тронуто++;
    }
  }
  if (тронуто) {
    fs.writeFileSync(реестр, JSON.stringify(j, null, 2) + '\n');
    console.log(`  реестр домов: перенесено записей ${тронуто}`);
  }
}

console.log(`\n✓ переименовано мест: ${правки.length}`);
console.log('  ТЕПЕРЬ ПРОВЕРЬТЕ СОДЕРЖАНИЕ: node tools/checks/content_probe.mjs');
