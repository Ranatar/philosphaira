-- 006 · Столкновения при применении.
--
-- Коммит, столкнувшийся с чужим, не отклоняется и не применяется наполовину:
-- он получает состояние conflicted, а РАЗБОР столкновения ложится сюда —
-- автору нужно видеть, какое поле разошлось и как, чтобы пересобрать коммит
-- поверх нынешнего состояния. Без этого «конфликт» — просто слово.
ALTER TABLE commits ADD COLUMN conflicts JSONB;
