-- РАСКЛАДКА ГРАФА — производное, но хранимое, и с историей.
--
-- ПОЧЕМУ ХРАНИМ. Раскладка детерминирована и зависит только от состава узлов
-- и связей, но считать её на клиенте нельзя: замерено, что один и тот же d3
-- в разных движках даёт разные раскладки на одних данных (медиана расхождения
-- 65 px). Если каждый считает сам, у всех выйдет своё, и общий язык про «вон
-- тот сгусток справа» пропадает. Для совместной работы это не мелочь.
--
-- ПОЧЕМУ С ИСТОРИЕЙ, А НЕ ОДНОЙ СТРОКОЙ. Перекладка меняет то, что люди видят
-- глазами, и без прежней раскладки откат был бы мнимым: координаты не
-- восстановить пересчётом — они зависят от всей истории приращений.
--
-- ПОЧЕМУ КЛЮЧ — ВЕРСИЯ ГРАФА, А НЕ ОТПЕЧАТОК БАЗЫ. У страницы отпечаток нужен
-- затем, что набор позиций и база едут порознь (файл и файл). Здесь они едут
-- вместе, одной транзакцией, и версия графа уже отвечает на вопрос «от какого
-- состояния эта раскладка». Второй ответ на тот же вопрос однажды разъедется
-- с первым.

CREATE TYPE layout_kind AS ENUM ('full', 'warm');

CREATE TABLE graph_layout (
  layout_id     BIGSERIAL PRIMARY KEY,

  -- Состояние графа, из которого раскладка получена.
  graph_version BIGINT NOT NULL,

  -- 'full' — полный отжиг с нуля (решение человека, редко);
  -- 'warm'  — дорасклад из прежних координат при утверждении коммита.
  kind          layout_kind NOT NULL,

  -- Прежняя раскладка, из которой дорастили. У полной — NULL.
  based_on      BIGINT REFERENCES graph_layout(layout_id) ON DELETE SET NULL,

  -- { "concept_id": [x, y], ... }. Округление до десятой доли: точность ниже
  -- пикселя ничего не значит, а шестнадцать знаков после запятой — просто шум.
  positions     JSONB NOT NULL CHECK (jsonb_typeof(positions) = 'object'),

  -- Кто вызвал перекладку. У дорасклада — тот, кто утвердил коммит.
  created_by    UUID REFERENCES users(user_id) ON DELETE SET NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  -- Мера расхождения с предыдущей раскладкой: медианный сдвиг узла и число
  -- узлов, уехавших дальше 200 px. Хранится, а не считается заново, потому
  -- что это ЧИСЛО РЕШЕНИЯ: по нему человек соглашался на перекладку.
  shift_median  REAL,
  shift_far     INTEGER
);

-- Действующая раскладка — последняя. Запрос идёт на каждое чтение графа.
CREATE INDEX graph_layout_recent ON graph_layout (layout_id DESC);

COMMENT ON TABLE graph_layout IS
  'Раскладка графа: координаты узлов с историей. Дорасклад при утверждении '
  'коммита, полная перекладка — решением человека.';
