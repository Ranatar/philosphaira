-- ОТПЕЧАТОК БАЗЫ ХРАНИТСЯ ВМЕСТЕ С РАСКЛАДКОЙ.
--
-- В 013 его нарочно не было: у сервера есть версия графа, и второй ответ на
-- вопрос «от какого состояния эта раскладка» однажды разъехался бы с первым.
-- Это по-прежнему верно — и поле здесь НЕ ДЛЯ ЭТОГО.
--
-- Отпечаток нужен СТРАНИЦЕ: в файле nodePositions.json набор и база едут
-- порознь, и страница проверяет их согласие отпечатком. Сервер его не
-- считает и считать не должен — правило живёт в исходнике. Он его ПЕРЕВОЗИТ:
-- принял при переносе семени, отдал при выгрузке.
--
-- Нашла нужду проверка развёртывания: выгруженный набор не совпадал с
-- семенем побайтово, потому что отпечаток терялся, и страница на таком
-- наборе откатилась бы на живую симуляцию.
ALTER TABLE graph_layout ADD COLUMN fingerprint TEXT;

COMMENT ON COLUMN graph_layout.fingerprint IS
  'Отпечаток базы со стороны страницы. Сервер его не вычисляет, а перевозит.';
