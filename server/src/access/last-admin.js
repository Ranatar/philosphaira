// Заслон «последний администратор».
//
// Считать администраторов ДО транзакции бессмысленно: два одновременных
// понижения оба увидят двоих и оба пройдут. Счёт берётся ВНУТРИ транзакции
// и с блокировкой — первый довод назван client не случайно (соглашение из
// src/db/tx.js).
//
// БЛОКИРУЮТСЯ ВСЕ ДЕЙСТВУЮЩИЕ АДМИНИСТРАТОРЫ, ВКЛЮЧАЯ ПРЕДМЕТ ДЕЙСТВИЯ.
// Первый набросок (беседа 1.2) блокировал «всех, кроме предмета» — казалось,
// что блокировать надо ровно тех, чьё исчезновение опасно. Замер ручной
// гонкой показал обратное: при двух одновременных понижениях РАЗНЫХ
// администраторов наборы блокировок не пересекались вовсе, оба заслона
// пропускали, а дальше сделки вставали друг на друге насмерть — и один
// запрос умирал по сроку, а не по правилу.
//
// Общий набор строк даёт то, ради чего заслон и нужен: вторая сделка ждёт
// первую, а дождавшись, перечитывает — и видит, что администратор остался
// один. Отказ приходит от ПРАВИЛА, а не от таймаута.
//
// Две команды вместо одной нарочно: FOR UPDATE не сочетается с count(),
// а читать поля строки за пределами src/db/ нельзя (правило, которое
// однажды здесь уже поймало пробу строения).

import { Conflict } from '../http/errors.js';

const ACTIVE_ROLES = `
  FROM users
   WHERE role = 'administrator'
     AND is_active AND NOT is_banned AND deleted_at IS NULL`;

export async function assertNotLastAdministrator(client, { userId, newRole = null }) {
  // Назначение администратором заслона не требует: их станет больше.
  if (newRole === 'administrator') return;

  // 1. Блокируем ВЕСЬ набор. Здесь вторая сделка и ждёт первую.
  await client.query(`SELECT 1 ${ACTIVE_ROLES} FOR UPDATE`);

  // 2. Считаем, сколько останется. Снимок нового запроса — уже с учётом
  //    того, что первая сделка успела закрепить.
  // rowCount, а не rows[0]: читать поля строки за пределами src/db/ нельзя,
  // и проба строения это стережёт. Считаем не count(), а число строк —
  // ответ тот же, а строка наружу не выходит.
  const { rowCount: останутся } = await client.query(
    `SELECT 1 ${ACTIVE_ROLES} AND user_id <> $1`, [userId]);

  if (останутся === 0) {
    throw new Conflict(
      'Это последний действующий администратор: сначала назначьте другого');
  }
}
